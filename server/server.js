// ── Auth middleware ─────────────────────────────────────────────────────
// Token must arrive either in `Authorization: Bearer <token>` or `?token=…`.
// `/health` is exempt so Tauri can poll the server before the frontend has
// fetched the token via IPC. Static asset requests (the frontend bundle and
// its CSS/JS) are exempt for the same reason — the webview loads them before
// any JS runs and there's no way to inject auth into a top-level navigation.
// Once the frontend boots, it pulls the token from Tauri and includes it on
// every API call + WS connection.
const PUBLIC_PATHS = new Set(['/health']);
function isStaticAsset(p) {
  return p === '/' || /\.(html|css|js|map|png|jpg|jpeg|gif|svg|ico|woff2?|ttf|otf)$/i.test(p);
}
app.use((req, res, next) => {
  if (process.env.KAIRO_ACCESS_LOG) console.log(`[REQ] ${req.method} ${req.path}`);
  if (!AUTH_REQUIRED) return next();
  if (PUBLIC_PATHS.has(req.path) || isStaticAsset(req.path)) return next();
  const hdr   = req.headers.authorization || '';
  const bearer = hdr.startsWith('Bearer ') ? hdr.slice(7) : null;
  const token = bearer || req.query.token;
  if (token === AUTH_TOKEN) return next();
  res.status(401).json({ error: 'unauthorized' });
});

app.use(express.static(path.join(__dirname, '..', 'src')));

// ── WebSocket upgrade gate ──────────────────────────────────────────────
// Validate the token in the upgrade URL before handing the socket to `wss`.
// Anything without the right token gets a 401 and the socket is destroyed.
server.on('upgrade', (req, socket, head) => {
  if (AUTH_REQUIRED) {
    const url = new URL(req.url, `http://${req.headers.host || '127.0.0.1'}`);
    if (url.searchParams.get('token') !== AUTH_TOKEN) {
      socket.write('HTTP/1.1 401 Unauthorized\r\n\r\n');
      socket.destroy();
      return;
    }
  }
  wss.handleUpgrade(req, socket, head, (ws) => wss.emit('connection', ws, req));
});

// ── WebSocket ─────────────────────────────────────────────────────────────
const clients = new Set();
wss.on('connection', (ws) => {
  clients.add(ws);
  ws.on('close', () => clients.delete(ws));
  ws.on('error', () => clients.delete(ws));
  // Send current worker status on connect
  ws.send(JSON.stringify({ type: 'worker-status', ready: workerBasicReady }));
  // Also send the current listening state — connection-state was previously
  // only ever broadcast on a CHANGE (start/stop/error), never as a snapshot
  // to a freshly (re)connected client. A client that reconnects after any
  // WS drop — a server restart, a network blip, the app losing focus — had
  // no way to learn the server's actual current state, so it just kept
  // whatever isListening it had cached from before the drop. Real incident:
  // restarting the server left a client showing a stale "Stop Listening"
  // button (from before the drop) against a fresh server process with no
  // active session at all — clicking it correctly posted to
  // /api/stop-listening, but there was nothing to stop, so nothing
  // happened, and the actual "Start" the user needed had no visible way in.
  ws.send(JSON.stringify({ type: 'connection-state', state: connectionState }));

  // Forward binary audio frames to whichever engine is active.
  // - Deepgram: streamed straight to the WS connection (Deepgram does endpointing)
  // - Whisper:  fed to the local recognizer; partial()/final() drive detection
  // Either way we keep a short audio ring buffer for the REST fallback path.
  ws.on('message', (data, isBinary) => {
    if (!isBinary) {
      // The only text messages a client sends are the display window
      // reporting video playback state back up — relayed as-is so the main
      // window's media controls can reflect real position without polling.
      try {
        const msg = JSON.parse(data.toString());
        if (msg.type === 'media-status') broadcast(msg);
      } catch {}
      return;
    }
    const chunk = Buffer.isBuffer(data) ? data : Buffer.from(data);
    if (deepgramConnection) {
      try { deepgramConnection.send(chunk); } catch {}
    } else if (whisperActive) {
      feedWhisperAudio(chunk);
    }
    audioRingBuffer.push({ data: chunk, time: Date.now() });
    audioRingBytes += chunk.length;
    while (audioRingBytes > AUDIO_RING_MAX_BYTES && audioRingBuffer.length) {
      audioRingBytes -= audioRingBuffer.shift().data.length;
    }
  });
});

function broadcast(data) {
  const msg = JSON.stringify(data);
  for (const ws of clients) {
    if (ws.readyState === ws.OPEN) ws.send(msg);
  }
}

