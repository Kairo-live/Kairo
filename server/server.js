// ── Verbatim phrase match ─────────────────────────────────────────────────
// Run on punctuation-split clauses so the preacher's intro ("as Paul writes,")
// doesn't dilute the phrase window.
// Single batch worker call — all clauses sent at once, worker returns best result.
function buildClauseList(text, minWords) {
  const clauses = text
    .split(/[.!?,;]/)
    .map(c => c.trim())
    .filter(c => c.split(RE_SPACES).filter(Boolean).length >= minWords);
  // De-duplicate and put the full text last as a fallback
  const unique = [...new Set([...clauses, text])];
  return unique.filter(c => c.split(RE_SPACES).filter(Boolean).length >= minWords);
}

async function processVerbatim(transcript) {
  try {
    const texts = buildClauseList(transcript, 6);
    if (!texts.length) return false;
    // Single round-trip — worker iterates all clauses internally
    const msg     = await workerCall('verbatimSearchBatch', { texts, minWords: 6, limit: 3 }, 4000);
    const results = msg.results || [];
    if (!results.length) return false;
    const viewer = results.filter(r => r.similarity >= VERBATIM_AUTOSEND_MIN || r.matchedIdf >= VERBATIM_CERTAIN_IDF);
    if (viewer.length) {
      const top    = viewer[0];
      const vKey   = `${top.book}|${top.chapter}|${top.verse}`;
      const corrected = maybeCorrectMiscitation(top, transcript);
      if (corrected) return true;   // replaced on-air, skip the normal viewer broadcast
      const viaIdf = top.similarity < VERBATIM_AUTOSEND_MIN;
      // top.similarity itself stays coverage-diluted (76% is an honest
      // reflection of "we only heard part of the verse") — that's still
      // true and worth keeping for display/logging. But the SEND decision
      // now runs on identification certainty, not completeness, so the
      // score actually used for the auto-send gate needs to reflect that
      // certainty too, or broadcastDetection's own VIEWER_MIN_SCORE check
      // would just demote it straight back to Candidates and undo this.
      const effectiveScore = viaIdf ? Math.max(top.similarity, 0.90) : top.similarity;
      const boosted = ensembleScore(vKey, 'verbatim', effectiveScore, viewer);
      const sent = await broadcastDetection(viewer, 'verbatim', boosted, 'viewer');
      // Logged after the call, gated on the ACTUAL landing target —
      // broadcastDetection returns 'viewer'/'suggestions'/false now, not a
      // plain boolean. It used to be a boolean, and `if (sent)` was true
      // whenever the continuity gate demoted this to Candidates too (it
      // still successfully broadcasts, just to 'suggestions'), which
      // printed a false "→ viewer" in the same breath as the [Guard]
      // line reporting it was blocked. Real incident this caused: Matthew
      // 20:17 logged "boosted=90% → viewer" one line after "[Guard]
      // Blocked non-sequential auto-send ... demoted to Candidates" for
      // the exact same detection.
      if (sent === 'viewer') console.log(`[Verbatim] "${top.reference}" raw=${(top.similarity*100).toFixed(0)}% boosted=${(boosted*100).toFixed(0)}%${viaIdf ? ` (via matchedIdf=${top.matchedIdf.toFixed(1)}, sequence-certain despite partial coverage)` : ''} → viewer`);
      // Feed high-confidence verbatim hits into sermon context + reading mode tracker
      if (top.similarity >= 0.92) {
        updateSermonContext({ book: top.book, chapter: top.chapter, verse: top.verse });
        trackReadingModeHit(top, top.similarity);
      }
    } else if (results[0]) {
      // Below the auto-send bar but still worth a human's attention — a 75%+
      // verbatim near-miss (scoring is IDF-weighted now, so this means
      // "probably right, missing a bit of the verse's identifying content")
      // used to just vanish with zero trace. Land it in Candidates instead;
      // broadcastDetection's own suggestion floor silently drops anything
      // weaker than that, so the log line reflects which outcome actually
      // happens rather than always claiming "candidates".
      //
      // Logged AFTER broadcastDetection now, using its real return value —
      // not predicted beforehand from `similarity >= SUGGESTION_MIN_SCORE`.
      // That predicted text went stale the moment bug #26's fix made this
      // gate conditional on useUnifiedScoring: under the new model, the
      // real floor is detectionScoring.decideTarget's own 0.50, not
      // SUGGESTION_MIN_SCORE (0.87) — so the old prediction would claim
      // "dropped" for entries that actually reached Candidates just fine.
      const sent = await broadcastDetection(results.slice(0, 1), 'verbatim', results[0].similarity, 'suggestions');
      console.log(`[Verbatim] "${results[0].reference}" raw=${(results[0].similarity*100).toFixed(0)}% — below ${(VERBATIM_AUTOSEND_MIN*100).toFixed(0)}% auto-send bar, ${sent === 'suggestions' ? '→ candidates' : 'dropped'}`);
    }
    return true;
  } catch { return false; }
}

// If the preacher just cited scripture X but is now reading scripture Y
// verbatim with high confidence, Y is almost certainly what they meant.
// Replace on-air with Y and tag it as a correction so the operator sees what
// happened. Returns true if a correction fired (caller should skip the normal
// broadcast path).
// How much matched IDF weight is trusted to correct an on-screen citation
// on its own, independent of raw similarity — same principle as
// VERBATIM_CERTAIN_IDF. Set just above ANCHOR_CONFIRM_IDF (12) — that's
// already the bar this codebase trusts to auto-send a BRAND NEW verse from
// a cold, unestablished session; trusting a similar bar to correct WITHIN
// an already-cited context (a narrower, arguably safer situation) is
// consistent, not looser. First calibrated at 22 from principle alone, then
// found empirically too high: a confirmed real mis-citation (cited Luke
// 6:14, actually reading Luke 4:14) scored matchedIdf=16.7 and got wrongly
// left uncorrected until this was lowered.
const CORRECTION_MIN_IDF = 15;

function maybeCorrectMiscitation(topMatch, sourceText) {
  if (settings.autoCorrect === false) return false;
  if (!lastDirectSentVerse) return false;
  const now = Date.now();
  if (wordsHeard - lastDirectSentWords > CORRECTION_WINDOW_WORDS) return false;
  if (now - lastDirectSentTime < CORRECTION_IMMUNITY_MS) return false;

  // If the cited book has ALREADY been independently reconfirmed by a
  // separate viewer-landing detection since the citation went out, the
  // citation is validated — the preacher really is reading that passage —
  // so a later, different-book match isn't "the truth behind a garbled
  // citation," it's just unrelated noise/overlap and shouldn't retroactively
  // erase a verse that's already been confirmed correct twice over.
  // lastDetectedRef/Time (not lastSentBook/lastSentBookTime — that pair is
  // gated behind the OUTPUT dedup, a separate concern, and stayed frozen at
  // the citation's own send in the exact case this exists for) update
  // unconditionally whenever a *different* verse lands on viewer, deduped
  // output or not. Real incident: "Ephesians 3:17-19" cited and its range
  // actively advancing, "Ephesians 3:18" independently confirmed via stream
  // moments later — then an unrelated "Psalms 112:3" match (previously
  // Guard-blocked as noise three times in the same log) "corrected" 3:17
  // right off the Live Queue mid-range. A genuine mis-citation never gets
  // this reconfirmation, since nothing else in the wrongly-cited book is
  // actually being read — lastDetectedTime stays equal to lastDirectSentTime
  // (same event, the citation itself), so this only screens out the
  // false-positive pattern.
  const lastDetectedBook = lastDetectedRef ? lastDetectedRef.split('|')[0] : null;
  if (lastDetectedBook === lastDirectSentVerse.book && lastDetectedTime > lastDirectSentTime) return false;

  // topMatch itself is already the thing on screen — nothing left to
  // correct. The Guard's own stale-override (3x independent re-detection)
  // already promotes a repeatedly-confirmed candidate to viewer on its own;
  // once that's happened, a LATER, redundant detection pass for that exact
  // same verse still reaches here (the same candidate keeps getting
  // re-detected as the preacher keeps reading it) and — since that send
  // updated lastDetectedRef to the NEW verse, not the original citation's
  // book — the book-reconfirmation check above no longer protects the
  // original citation either. Real incident: "Matthew 13:44" cited,
  // "Proverbs 3:19" independently re-detected 3x and let through by the
  // stale-override straight to viewer, then a later repeat pass for that
  // same already-showing "Proverbs 3:19" ran through here too and fired a
  // second, redundant "correction" — displaying nothing new but retro-
  // actively erasing "Matthew 13:44" from the Live Queue's history anyway.
  const topKey = `${topMatch.book}|${topMatch.chapter}|${topMatch.verse}`;
  if (topKey === lastDetectedRef) return false;

  // If the text driving THIS match itself names the new book out loud, the
  // preacher is announcing a fresh citation, not silently misquoting one —
  // let the normal direct-citation path own it (it'll send its own
  // "[Direct]" a moment later once it finishes parsing chapter/verse) rather
  // than smashing it into a "correction" of whatever was cited before. Real
  // incident this caused: preacher explicitly cited "2 Corinthians 4:4",
  // finished that point, then explicitly cited "Matthew chapter 17 and
  // verse 21" and began quoting it — the stream detector matched the quoted
  // content before the direct parser finished joining the split citation
  // phrase, so this fired first and erased the (correct, unrelated)
  // 2 Corinthians 4:4 card from the Live Queue under a false "corrected"
  // label. Only checked when sourceText is actually a fresh citation
  // attempt; quoted content with no book name (the real mis-citation case —
  // "John 10:1" cited, Psalm 121:1 actually read) is untouched by this.
  if (sourceText) {
    const mentioned = detectBookMentions(sourceText, true);
    if (mentioned.includes(topMatch.book) && topMatch.book !== lastDirectSentVerse.book) return false;
  }

  // Two independent ways to qualify: very high raw similarity (verbatim's
  // own semantics), or very high absolute matched-IDF weight (stream's).
  // Neither alone should be lowered — this ADDS a second acceptance path
  // rather than loosening the first.
  const strongEnough = topMatch.similarity >= CORRECTION_MIN_SIMILARITY
    || (topMatch.matchedIdf != null && topMatch.matchedIdf >= CORRECTION_MIN_IDF);
  if (!strongEnough) return false;

  const sameVerse = topMatch.book === lastDirectSentVerse.book
                 && topMatch.chapter === lastDirectSentVerse.chapter
                 && topMatch.verse === lastDirectSentVerse.verse;
  if (sameVerse) return false;   // verbatim agrees with what was cited — nothing to correct

  // Never "correct" small forward progress within the SAME book+chapter as
  // what was cited — that isn't a mis-citation, it's the preacher continuing
  // to read (same principle as the continuity gate's same-chapter fast-path).
  // This has to hold whether or not the original citation was a formal
  // multi-verse range: checking membership in rangeAllVerses alone missed
  // it for a plain single-verse citation ("Ezekiel 47:1") followed by the
  // preacher just continuing to verse 2, 3... with no re-citation — there's
  // no range object to check membership against in that case, only
  // lastDirectSentVerse itself. Real regression this caused: verse 1 of a
  // genuinely correct citation/range got "corrected" to a later verse in
  // that SAME passage, which doesn't just mis-score it — showInViewer
  // removes the correctedFrom card from the Live Queue entirely, silently
  // erasing a verse that was correctly on screen. Backward moves and any
  // different book/chapter stay eligible — only same-book-same-chapter
  // forward is excluded, since that's the one case the normal continuity
  // path already handles correctly on its own.
  // BUT capped at MISCITATION_FORWARD_EXEMPT_VERSES — real incident: "Genesis
  // 24 verse 3" cited (Deepgram dropped "sixty" from "sixty-three"), the
  // verbatim text actually being read ("Isaac went out to meditate in the
  // field") strongly matched Genesis 24:63 — 60 verses ahead in the SAME
  // chapter, so this exemption (with no distance limit) treated a flatly
  // wrong citation number as "just reading forward" and never corrected it.
  // Within the tight ~35-word window this whole function only ever runs in,
  // a SMALL forward jump is genuine continued reading; a LARGE one is far
  // more likely a misheard verse number than 60 verses read in a few
  // spoken sentences.
  const forwardWithinCitedChapter = topMatch.book === lastDirectSentVerse.book
    && topMatch.chapter === lastDirectSentVerse.chapter
    && topMatch.verse > lastDirectSentVerse.verse
    && topMatch.verse - lastDirectSentVerse.verse <= MISCITATION_FORWARD_EXEMPT_VERSES;
  if (forwardWithinCitedChapter) return false;
  const withinEstablishedRange = rangeAllVerses.some(v =>
    v.book === topMatch.book && v.chapter === topMatch.chapter);
  if (withinEstablishedRange) return false;

  // Duplicate/overlapping phrasing between two DIFFERENT verses — the same
  // class of collision processStreamText's own tie-guard already protects
  // against for two candidates open at once (Psalms 14/53, Ps 18/2 Sam 22,
  // etc.), just showing up here as one candidate wrongly "correcting" an
  // already-correct citation instead. Real incident: preacher correctly
  // cited and was still reading Joshua 1:8 ("...shall not depart out of thy
  // mouth..."); the closing words alone also matched Isaiah 59:21 (which
  // closes with the near-identical "...shall not depart out of thy
  // mouth...") at matchedIdf=15.2 — barely above CORRECTION_MIN_IDF — and
  // wrongly replaced the correct citation. Simply raising CORRECTION_MIN_IDF
  // isn't safe: the real Luke 6:14/Luke 4:14 mis-citation this bar was
  // ALREADY tuned against (see its own comment above) scored matchedIdf=16.7
  // — barely below Isaiah 59:21's 15.2, too close to separate with one
  // number. Checking phrase overlap instead is the actually-distinguishing
  // signal: if most of what was just heard is ALSO explained by the verse
  // ALREADY correctly on screen, this reads as two verses sharing wording,
  // not a real switch to something else — the genuine Luke 4:14 case has no
  // such overlap with Luke 6:14's own (different) text, so it still
  // corrects normally.
  if (sourceText && lastDirectSentVerse.text) {
    const spokenWords = meaningfulWords(sourceText);
    if (spokenWords.length) {
      const citedWords = new Set(meaningfulWords(lastDirectSentVerse.text));
      const overlap = spokenWords.filter(w => citedWords.has(w)).length;
      if (overlap / spokenWords.length >= 0.7) return false;
    }
  }

  // No book/chapter/distance restriction — this app is meant to be a
  // source of truth for what was actually SAID, not what was CITED. A
  // preacher citing "John 10:1" but actually reading Psalm 121:1 needs to
  // self-correct regardless of how far the citation and the real content
  // are apart; requiring "same chapter, verse ±2" (the old restriction)
  // only ever catches the narrowest case (a mis-remembered verse number)
  // and leaves every mis-heard BOOK or CHAPTER — the far more common
  // failure, since Deepgram garbles chapter/verse digits constantly —
  // stuck on screen with no way to self-correct. What makes this safe
  // instead is the confidence bar above: routine isolated phrase overlap
  // never reaches CORRECTION_MIN_SIMILARITY or CORRECTION_MIN_IDF by
  // accident — those thresholds are the actual safety net now, not
  // proximity to the (possibly wrong) citation.

  const correctedFrom = lastDirectSentVerse.reference;
  const viaIdf = topMatch.similarity < CORRECTION_MIN_SIMILARITY;
  console.log(`[Correct] Replacing "${correctedFrom}" with ${topMatch.method || 'verbatim'} hit "${topMatch.reference}" (${(topMatch.similarity*100).toFixed(0)}%${viaIdf ? `, via matchedIdf=${topMatch.matchedIdf.toFixed(1)}` : ''})`);

  // See recentlyCorrectedAway's own declaration comment — a fresh 'direct'
  // re-parse of this exact OLD reference (the same garbled words re-surfacing
  // from a joined-segment retry) shouldn't blindly overwrite this correction.
  recentlyCorrectedAway = {
    key: `${lastDirectSentVerse.book}|${lastDirectSentVerse.chapter}|${lastDirectSentVerse.verse}`,
    replacedByKey: `${topMatch.book}|${topMatch.chapter}|${topMatch.verse}`,
    replacedByReference: topMatch.reference,
    at: Date.now(),
  };

  // Consume the window so we don't repeatedly correct from the same stale ref.
  lastDirectSentVerse = null;
  lastDirectSentTime  = 0;

  const correctedVerse = { ...topMatch, correctedFrom };
  broadcast({
    type: 'detection',
    verses: [correctedVerse],
    method: topMatch.method || 'verbatim',
    topScore: topMatch.similarity,
    target: 'viewer',
    corrected: true,
    correctedFrom,
    timestamp: now,
  });

  // Push to outputs directly — bypass broadcastDetection's same-key dedup since
  // we specifically want to replace the mis-cited verse on ProPresenter/OBS.
  lastSentBook       = topMatch.book;
  lastSentBookTime   = now;
  lastDetectedRef    = `${topMatch.book}|${topMatch.chapter}|${topMatch.verse}`;
  lastDetectedTime   = now;
  lastDetectedMethod = topMatch.method || 'verbatim';
  sendToOutputs(topMatch).catch(err => console.warn('[Server] sendToOutputs (correction) failed:', err.message));
  return true;
}

// skipNewTranscriptCheck: true on interim path
async function runFingerprintSearch(currentSegment, skipNewTranscriptCheck = false) {
  if (!workerBasicReady) return;
  if (!skipNewTranscriptCheck && !hasNewTranscript) return;
  if (!skipNewTranscriptCheck) hasNewTranscript = false;

  // Combined window: recent non-reference buffer + current segment (last 40 words)
  const bufferText = transcriptBuffer
    .filter(t => !t.hasRef)
    .map(t => t.text)
    .join(' ');
  const combined = [bufferText, currentSegment].filter(Boolean).join(' ').trim();

  // Clause segmentation — filter out clauses with book names (reference parser owns those)
  const rawClauses = combined
    .split(/[.!?,;]/)
    .map(c => c.trim())
    .filter(c => c.split(RE_SPACES).filter(Boolean).length >= 4)
    .filter(c => {
      const ws = c.toLowerCase().split(RE_SPACES);
      return !ws.some(w => SINGLE_WORD_BOOKS.has(w.replace(/[^a-z]/g, '')));
    });

  const fallback = combined.split(RE_SPACES).slice(-40).join(' ');
  const fallbackHasBook = fallback.toLowerCase().split(RE_SPACES)
    .some(w => SINGLE_WORD_BOOKS.has(w.replace(/[^a-z]/g, '')));

  // Most recent clauses first, full window as last fallback
  const texts = [...new Set([
    ...rawClauses.reverse(),
    ...(!fallbackHasBook ? [fallback] : []),
  ])].filter(t => t.split(RE_SPACES).filter(Boolean).length >= 4);

  if (!texts.length) return;

  try {
    const contextHint     = getContextHint();
    const recentDirectRef = Date.now() - lastDirectRefTime < DIRECT_REF_SUPPRESS_MS;

    if (contextHint) {
      const top = contextHint.citations[0];
      // Log only when the nearest citation (or the count) actually changes —
      // the age-in-seconds ticking up on its own isn't new information worth
      // a fresh line every second for the whole service.
      const key = `${contextHint.citations.length}|${top.book}|${top.chapter}|${top.verse}`;
      if (key !== lastLoggedContextKey) {
        lastLoggedContextKey = key;
        console.log(`[Context] ${contextHint.citations.length} citation(s) — nearest: ${top.book} ${top.chapter}:${top.verse}`);
      }
    }

    // Single round-trip — worker iterates all clauses and returns best result
    const msg        = await workerCall('fingerprintSearchBatch', { texts, limit: 5, contextHint }, 3000);
    const results    = msg.results || [];
    const confidence = msg.confidence || 'none';

    if (!results.length || confidence === 'none') return;

    // Fingerprint (context/paraphrase) hits only ever surface as Candidates
    // suggestions — see the FINGERPRINT note above runFingerprintSearch for why
    // they never auto-deploy. Suppressed briefly after a direct citation so the
    // operator isn't shown a redundant "context" suggestion for a verse the
    // preacher just explicitly cited.
    // Reverted from a brief experiment at 0.80: real transcripts showed it let
    // through more wrong-verse noise without actually catching the paraphrases
    // it was meant to rescue — those scored well below even 0.80 (~55%), so the
    // lower floor bought nothing but noise. Raised again 0.85 → 0.87 to match
    // SUGGESTION_MIN_SCORE — the panel-wide floor is what should decide "worth
    // showing" now, not a fingerprint-specific number that happened to differ
    // from it by 2 points for no real reason.
    //
    // Show every result that clears the bar, not just the single best one
    // (was hard-capped at top-1 to fight noise, but that meant a genuinely
    // good second/third match never got a chance to show up either — the
    // bar itself is what should be doing the noise filtering, not an
    // arbitrary count cap). Still bounded (3) so a flood of near-tied
    // results can't overwhelm the panel.
    if (!recentDirectRef) {
      const qualifying = results.filter(r => r.similarity >= SUGGESTION_MIN_SCORE).slice(0, 3)
        .map(r => ({ ...r, similarity: ensembleScore(`${r.book}|${r.chapter}|${r.verse}`, 'fingerprint', r.similarity, results) }));
      if (qualifying.length) {
        // Logged AFTER broadcastDetection, gated on its own return value —
        // this used to log unconditionally before the call, which kept
        // printing "→ candidates" even on passes broadcastDetection's own
        // dedup silently swallowed (the same still-lingering verse re-
        // qualifying on nearly every search pass for a while), making a
        // single real suggestion look like dozens in the log.
        const sent = await broadcastDetection(qualifying, 'fingerprint', qualifying[0].similarity, 'suggestions');
        if (sent) console.log(`[Fingerprint] ${qualifying.map(r => `"${r.reference}" ${(r.similarity*100).toFixed(0)}%`).join(', ')} → candidates`);
        if (qualifying[0].similarity >= 0.87) {
          updateSermonContext({ book: qualifying[0].book, chapter: qualifying[0].chapter, verse: qualifying[0].verse });
        }
      }
    }
  } catch (err) {
    if (!err.message?.includes('timeout')) {
      console.warn('[Server] Fingerprint search error:', err.message);
    }
  }
}

// ── Semantic search (meaning-based Candidates) ─────────────────────────────
// The "Idea-Matcher" — unlike fingerprint (shared vocabulary) this compares
// MEANING via embeddinggemma-300m, so a paraphrase that shares almost no
// literal words with a verse can still surface it. Suggestions-only, same
// as fingerprint: this never drives an auto-send decision, it only ever
// populates Candidates for a human to glance at and promote.
//
// Started at 0.78 (the gap between 0.83-0.95 genuine-match and 0.65-0.73
// unrelated-pair scores on held-out test phrases). Raised to match
// SUGGESTION_MIN_SCORE (0.87) at the operator's request after real services
// showed too much noise getting through — this does mean some genuine
// paraphrase matches in the 0.78-0.87 range (a real, correct verse, just
// not phrased close enough to score higher) now get filtered out too.
// That's a deliberate precision-over-recall tradeoff, not an oversight: a
// human always sees the transcript and can act on their own knowledge — a
// suggestion panel that's wrong often enough to ignore helps no one, even
// if raising the bar costs a few correct-but-lower-confidence calls.
const SEMANTIC_MIN_SCORE      = SUGGESTION_MIN_SCORE;
let lastSemanticSearch        = 0;
const SEMANTIC_INTERVAL_MS    = 2000;   // heavier than fingerprint (embedding + 31k-vector scan) — don't run more than once per 2s

async function runSemanticSearch(text) {
  if (!workerSemanticReady) return;
  const words = text.split(RE_SPACES).filter(Boolean);
  if (words.length < 5) return;   // too short to embed meaningfully

  try {
    const recentDirectRef = Date.now() - lastDirectRefTime < DIRECT_REF_SUPPRESS_MS;
    if (recentDirectRef) return;   // same suppression fingerprint uses — don't second-guess a citation just made

    const msg     = await workerCall('semanticSearch', { text, limit: 5 }, 3000);
    const results = msg.results || [];
    if (!results.length) return;

    // Same reasoning as fingerprint above — show everything that clears the
    // bar (bounded to 3), not just the single top hit.
    const qualifying = results.filter(r => r.similarity >= SEMANTIC_MIN_SCORE).slice(0, 3)
      .map(r => ({ ...r, similarity: ensembleScore(`${r.book}|${r.chapter}|${r.verse}`, 'semantic', r.similarity, results) }));
    if (!qualifying.length) return;
    // See the matching comment in runFingerprintSearch — logged after the
    // call, gated on whether anything actually reached the UI.
    const sent = await broadcastDetection(qualifying, 'semantic', qualifying[0].similarity, 'suggestions');
    if (sent) console.log(`[Semantic] ${qualifying.map(r => `"${r.reference}" ${(r.similarity*100).toFixed(0)}%`).join(', ')} → candidates`);
  } catch (err) {
    if (!err.message?.includes('timeout')) {
      console.warn('[Server] Semantic search error:', err.message);
    }
  }
}

function confidenceRank(c) {
  return c === 'high' ? 3 : c === 'medium' ? 2 : c === 'low' ? 1 : 0;
}

// ── Ensemble scorer ────────────────────────────────────────────────────────
// Called from processVerbatim and runFingerprintSearch before broadcasting.
// Returns boosted score if another method already detected this verse recently.
function ensembleScore(verseKey, method, score, verses) {
  if (!verseKey) return score;
  const now = Date.now();

  // Clean stale entries
  for (const [key, entry] of ensembleCache) {
    if (now - entry.time > ENSEMBLE_WINDOW_MS) ensembleCache.delete(key);
  }

  const existing = ensembleCache.get(verseKey);
  if (existing && existing.method !== method && now - existing.time <= ENSEMBLE_WINDOW_MS) {
    // Two different methods agree — boost
    const boosted = Math.min(1.0, Math.max(score, existing.score) + ENSEMBLE_BOOST);
    console.log(`[Ensemble] ${existing.method}+${method} agree on ${verseKey} → ${(boosted*100).toFixed(0)}%`);
    ensembleCache.delete(verseKey); // consume — don't triple-boost
    return boosted;
  }

  // Store for future agreement
  ensembleCache.set(verseKey, { score, method, verses, time: now });
  return score;
}

async function broadcastDetection(verses, method, topScore, target) {
  const now    = Date.now();
  const topKey = verses[0] ? `${verses[0].book}|${verses[0].chapter}|${verses[0].verse}` : null;

  // A range is active and this candidate — from ANY method, not just an
  // explicit citation — is exactly the range's own next-expected verse:
  // advance immediately rather than falling through to the general scoring
  // path below. See tryRangeAdvanceByDetection's own comment for the real
  // incident this fixes. Runs first so it takes priority even over a
  // candidate that would otherwise be demoted or dropped by the checks
  // below — being the range's known next verse is stronger evidence than
  // any of those generic heuristics can see.
  if (tryRangeAdvanceByDetection(verses, topScore)) return 'viewer';

  // ── Score gate ────────────────────────────────────────────────────────────
  // Low-confidence detections must never auto-send to the live display.
  // Demote to suggestions so the operator can still see and promote manually.
  if (target === 'viewer' && topScore < VIEWER_MIN_SCORE) {
    target = 'suggestions';
  }

  // ── Continuity gate ────────────────────────────────────────────────────────
  // A fuzzy (verbatim/fingerprint) hit is only trusted to auto-send while a
  // book is "active" (something was sent in the last SAME_BOOK_WINDOW_MS) if
  // it is the *immediate next verse* in that same book/chapter — the one
  // legitimate case this needs to cover automatically is a preacher reading
  // straight down a passage. Anything else — a different book, a different
  // chapter, or a verse that isn't simply current+1 — is far more likely to
  // be an isolated word-overlap false positive than a real, un-cited jump;
  // a genuine topic/passage change is always cited explicitly (method
  // 'direct'), never inferred from a phrase match alone. Demote instead of
  // drop: the operator still sees it and can promote it manually from
  // Candidates if it's genuinely right.
  // ANY non-'direct' method must ALWAYS pass through this gate, including on
  // the very first detection of a session when lastSentBook isn't set yet —
  // this used to only apply once a book was already "active" (something
  // sent within SAME_BOOK_WINDOW_MS), on the reasoning that "nothing to be
  // non-sequential relative to" meant nothing to guard against. Two separate
  // real incidents proved that wrong: 'direct-partial' auto-sent "Esther
  // 6:1" at 100% from an STT-hallucinated book context (fixed by special-
  // casing that one method), then 'stream' independently did the same thing
  // to "Acts 3:6" (matchedIdf=13.0, a phrase collision on "in the name of
  // Jesus Christ of Nazareth") as literally the first detection of a later
  // session — the special-case for 'direct-partial' alone didn't cover it,
  // because the free pass was never about which method, it was about
  // whether lastSentBook existed yet. A single ungated hit — of any kind —
  // becoming "active" then blocks every correct detection that follows
  // until it independently re-confirms 3x, which is exactly what turned
  // this into a visible delay on the genuinely correct Psalms 92:13 right
  // after Acts 3:6 wrongly went out. isSequential below is already false
  // whenever lastOutputVerse is null, so removing the outer gate here
  // doesn't change behavior for anything that WAS legitimately sequential —
  // it just means a cold-start hit needs the same 3x-independent-
  // reconfirmation (or an actual 'direct' citation) as any other non-
  // sequential one, instead of a free pass for being first.
  if (target === 'viewer' && method !== 'direct' && verses[0]) {
    const bookActiveRecently = !!lastSentBook && now - lastSentBookTime < SAME_BOOK_WINDOW_MS;
    // "Next verse" (reading forward) OR the SAME verse already on screen —
    // the latter matters because two independent methods (e.g. the anchor
    // trie and verbatim) can both correctly land on the verse that's ALREADY
    // showing within the same moment; without this, the second, entirely
    // correct confirmation gets treated as "non-sequential" purely because
    // verse === current, not current+1, and gets needlessly demoted despite
    // agreeing with what's already right on screen.
    // Forward-within-the-same-chapter (verse >= current), not just exactly
    // current+1 — a preacher skipping ahead a few verses while explaining
    // (Genesis 41:38 → 44, Daniel 10:3 → 12) is completely normal reading,
    // and a coincidental word-overlap match landing in the SAME chapter
    // already-being-read is far less likely than one landing in a
    // different book entirely. Widening this from strictly +1 measurably
    // speeds up real sends: batch-testing against real sermon audio showed
    // 7-18% of correct detections per service were only reaching the
    // screen via the slower 3x-reconfirm override path purely because they
    // skipped a few verses ahead within a chapter the preacher was already
    // reading straight through. Backward jumps are still never trusted
    // here (see isBackwardInSameBook below) — this only widens forward.
    const isSequential = bookActiveRecently && lastOutputVerse
      && verses[0].book    === lastOutputVerse.book
      && verses[0].chapter === lastOutputVerse.chapter
      && verses[0].verse   >= lastOutputVerse.verse;
    // A verse BEHIND the one currently active, in the same book/chapter, is
    // never eligible for the stale-override below — real incident: reading
    // forward through a range, a phrase echoing an EARLIER verse in that
    // same range got independently re-detected 3x (the preacher circling
    // back to a word, or a plain word-overlap collision) and the override
    // treated that exactly like the Psalm 110/111 case it exists for,
    // yanking the display backward to a verse already read. The override's
    // whole premise — "this keeps reasserting itself against a WRONG active
    // reference, so it's probably the truth trying to get through" — only
    // holds for catching up or jumping to a different book; going backward
    // within a passage you're actively reading forward through is never
    // that, so it just stays a Candidate no matter how many times it repeats.
    // Only blocks a genuine RE-send of a verse that's actually already been
    // shown (sentVerseKeysThisBook) — not any verse merely numbered below
    // whatever's on screen. Real incident this widening fixes: a preacher
    // citing a passage's LAST verse first (its "reference"), then reading
    // the whole thing from the top — Matthew 15:23-27 read in full, in
    // order, at 90-99% confidence each, every single one silently dropped
    // because verse 28 (the punch line, cited/paraphrased earlier) was
    // already active. Those earlier verses were legitimately SKIPPED, never
    // shown, so re-detecting them isn't the stale-backward-jump case at
    // all — it's exactly the "catching up" case the override exists for.
    const isBackwardInSameBook = lastOutputVerse
      && verses[0].book    === lastOutputVerse.book
      && verses[0].chapter === lastOutputVerse.chapter
      && verses[0].verse   <  lastOutputVerse.verse
      && sentVerseKeysThisBook.has(topKey);
    if (!isSequential) {
      // Track repeated independent re-detection of this exact non-active
      // verse — see the comment on staleOverrideCandidate above.
      if (staleOverrideCandidate && staleOverrideCandidate.key === topKey
          && now - staleOverrideCandidate.lastSeenAt < STALE_OVERRIDE_WINDOW_MS) {
        staleOverrideCandidate.count++;
        staleOverrideCandidate.lastSeenAt = now;
        staleOverrideCandidate.methods.add(method);
      } else {
        staleOverrideCandidate = { key: topKey, count: 1, lastSeenAt: now, methods: new Set([method]) };
      }

      // Cross-method agreement is stronger evidence than the same method
      // repeating: two independent detection layers (e.g. the anchor-trie
      // 'stream' pass and the phrase-alignment 'verbatim' pass) landing on
      // the same verse from the same transcript rules out one method's own
      // idiosyncratic false-positive pattern just recurring — which is
      // exactly the risk STALE_OVERRIDE_COUNT's same-method 3x exists to
      // catch. Real incident this addresses: a heavily STT-garbled spoken
      // citation ("January of the thirtieth of the seventeen" for
      // "Jeremiah 30:17") never resolves to a 'direct' hit, so a genuinely
      // correct, sequence-certain verbatim match had to sit through 3 full
      // independent re-detections before reaching the screen — a multi-
      // second lag on something two different layers already agreed on
      // within the same breath. Two methods agreeing needs only 2 hits
      // total, not 3 of the same one.
      const crossMethodConfirmed = staleOverrideCandidate.methods.size >= 2 && staleOverrideCandidate.count >= 2;

      // Book-momentum: see bookMomentumCandidate's own declaration comment.
      // Distinct ASCENDING verses (never a scattered/backward hit) in the
      // same new book+chapter, independent of the exact-key tracking above.
      if (bookMomentumCandidate && bookMomentumCandidate.book === verses[0].book
          && bookMomentumCandidate.chapter === verses[0].chapter
          && now - bookMomentumCandidate.lastSeenAt < STALE_OVERRIDE_WINDOW_MS) {
        if (verses[0].verse >= Math.max(...bookMomentumCandidate.verses)) {
          bookMomentumCandidate.verses.add(verses[0].verse);
          bookMomentumCandidate.lastSeenAt = now;
        }
      } else {
        bookMomentumCandidate = { book: verses[0].book, chapter: verses[0].chapter, verses: new Set([verses[0].verse]), lastSeenAt: now };
      }
      const bookMomentumConfirmed = bookMomentumCandidate.verses.size >= 2;

      if ((staleOverrideCandidate.count >= STALE_OVERRIDE_COUNT || crossMethodConfirmed || bookMomentumConfirmed) && !isBackwardInSameBook) {
        const via = staleOverrideCandidate.count >= STALE_OVERRIDE_COUNT
          ? `independently re-detected ${staleOverrideCandidate.count}x`
          : crossMethodConfirmed
            ? `${[...staleOverrideCandidate.methods].join('+')} agree`
            : `${bookMomentumCandidate.verses.size} ascending verses in ${verses[0].book} ${verses[0].chapter}`;
        console.log(`[Guard] Overriding stale active reference: "${verses[0].reference}" ${via} while "${lastSentBook || 'nothing'}" (last: ${lastOutputVerse?.reference || '?'}) sat active — letting it through`);
        // See recentlyCorrectedAway's own declaration comment — remember
        // that the OLD (stale) active reference was just superseded, so a
        // fresh 'direct' re-parse of that exact same old reference doesn't
        // blindly overwrite this correction moments later.
        if (lastOutputVerse) {
          recentlyCorrectedAway = {
            key: `${lastOutputVerse.book}|${lastOutputVerse.chapter}|${lastOutputVerse.verse}`,
            replacedByKey: topKey,
            replacedByReference: verses[0].reference,
            at: now,
          };
        }
        staleOverrideCandidate = null;   // consumed
        bookMomentumCandidate = null;    // consumed
      } else {
        const backwardNote = isBackwardInSameBook && staleOverrideCandidate.count >= STALE_OVERRIDE_COUNT
          ? ` (override count met but blocked — "${verses[0].reference}" is behind "${lastOutputVerse.reference}", never auto-sent)`
          : '';
        console.log(`[Guard] Blocked non-sequential auto-send: "${lastSentBook || 'nothing sent yet this session'}" active (last: ${lastOutputVerse?.reference || '?'}), ${method} hit "${verses[0].reference}" (${(topScore*100).toFixed(0)}%) — demoted to Candidates${backwardNote}`);
        target = 'suggestions';
      }
    } else if (staleOverrideCandidate && staleOverrideCandidate.key === topKey) {
      staleOverrideCandidate = null;   // it went through normally — stop tracking it
    }
  }

  // ── Consolidated scoring — shadow mode ──────────────────────────────────
  // Wrapped entirely in try/catch, touches no variable the real decision
  // above already used — a bug here can never affect what actually reaches
  // the operator's screen, only what gets logged for later review.
  try {
    if (verses[0]) {
      const candidate = { book: verses[0].book, chapter: verses[0].chapter, verse: verses[0].verse };
      const activeContext = lastOutputVerse
        ? { book: lastOutputVerse.book, chapter: lastOutputVerse.chapter, verse: lastOutputVerse.verse, t: lastSentBookTime }
        : null;
      const alreadyShown = (c) => sentVerseKeysThisBook.has(`${c.book}|${c.chapter}|${c.verse}`);
      const rawResult = {
        similarity: verses[0].similarity ?? topScore,
        matchedIdf: verses[0].matchedIdf,
        confidence: verses[0].confidence,
        confirmed: verses[0].confirmed,
        matched: verses[0].matched,
        // df/idf: only unconfirmed stream ANCHORS carry these (confirmed
        // alignments use matchedIdf instead) — needed for
        // calibrateMethodScore's df=1 unique-phrase case, which mirrors
        // processStreamText's own "Unique-phrase fast-share" policy below.
        df: verses[0].df,
        idf: verses[0].idf,
      };
      const { finalScore, breakdown } = detectionScoring.scoreCandidate(candidate, method, rawResult, {
        activeContext, alreadyShown, ledger: shadowLedger, now,
        // A formally-established range ("read verses 1 to 3") is a much
        // stronger "stay here" signal than ordinary continuity — see
        // scoreCandidate's own comment for the real incident (Jeremiah 17:8
        // / Romans 7:22, both near-duplicate phrasing with Psalm 1, hijacked
        // the display mid-range).
        rangeActiveBook: rangeCurrentVerse ? rangeCurrentVerse.book : null,
      });
      if (process.env.KAIRO_DEBUG_SCORING) console.log('[DEBUG-SCORING]', JSON.stringify({ candidate, method, rawResult, activeContext, rangeActiveBook: rangeCurrentVerse ? rangeCurrentVerse.book : null, finalScore, breakdown }));
      // Read corroboration BEFORE record() — same "don't corroborate
      // itself" ordering as scoreCandidate's own ledger.total() read above;
      // decideTarget's semantic exemption needs to know whether a DIFFERENT
      // method already, independently hit this exact verse, not whether
      // this candidate's own hit just got logged.
      const corroborated = shadowLedger.hasCorroboration(candidate);
      // Record AFTER scoring (not before) — this candidate's own hit
      // shouldn't corroborate itself; matches staleOverrideCandidate's
      // real ordering (checked, then updated) above.
      shadowLedger.record(candidate, method, now);
      const shadowTarget = detectionScoring.decideTarget(finalScore, method, { corroborated });
      if (shadowTarget !== target) {
        logDebug('scoring-shadow-divergence', {
          reference: verses[0].reference, method,
          oldTarget: target, newTarget: shadowTarget,
          oldScore: topScore, finalScore, breakdown,
        });
      }
      // Real cutover — default false (see the settings.autoSend/autoCorrect
      // pattern this mirrors). When on, the new model's decision REPLACES
      // target for everything below (suggestions dedup, viewer dedup,
      // broadcast, sendToOutputs) — the old gate logic above still runs
      // harmlessly alongside (still updating staleOverrideCandidate/
      // bookMomentumCandidate), which keeps shadow-log comparisons
      // meaningful in both modes and costs nothing but a few discarded
      // object mutations. topScore is also replaced so downstream logging
      // (and the suggestion-floor check just below) reflects the score
      // that actually drove the decision, not the old system's.
      if (settings.useUnifiedScoring === true) {
        target = shadowTarget;
        topScore = finalScore;
      }
    }
  } catch (err) {
    console.warn('[ScoringShadow] error (non-fatal, real decision unaffected):', err.message);
  }

  // Below the suggestions floor → drop entirely. Not useful enough to show anywhere.
  //
  // TWENTY-SIXTH bug — this check must NOT apply when useUnifiedScoring is
  // on. Owner, live: "candidate section never gets populated anymore...
  // context isn't doing its job." Root cause: decideTarget
  // (detection_scoring.js) already has its OWN correct floor for
  // 'suggestions' vs 'drop' — 0.50 on the new model's fused B+D+A scale,
  // an intentional, documented design choice (see decideTarget's own
  // comment). But this downstream check re-applies SUGGESTION_MIN_SCORE
  // (0.87) on top of it regardless — a constant calibrated for the OLD
  // system's raw per-method scores, on a completely different scale.
  // Net effect: ANYTHING decideTarget classified 'suggestions' with a
  // finalScore between 0.50 and 0.87 (the entire range decideTarget's own
  // floor exists to allow through) was silently re-dropped here, every
  // time, since the day useUnifiedScoring went live. Only a finalScore
  // that ALSO happened to clear 0.87 could ever actually reach the
  // Candidates panel — an accident of two thresholds from two different
  // eras of this codebase stacking, not a deliberate design. When
  // useUnifiedScoring is off, this check is exactly as intended (gating
  // the OLD system's own raw scores against the OLD system's own bar).
  if (settings.useUnifiedScoring !== true && target === 'suggestions' && topScore < SUGGESTION_MIN_SCORE) return false;
  // THIRTEENTH real bug found live, same session, via the owner's own
  // screenshot of the Candidates panel showing 33%/39%/40% entries that
  // never should have been visible at all. Confirmed via debug.log:
  // detectionScoring.decideTarget legitimately classifies these as
  // 'drop' (its OWN, stricter-than-'suggestions' floor) — but this file's
  // ONLY score gate above only fires `if (target === 'suggestions' ...)`.
  // Once useUnifiedScoring replaces `target` with the new model's 'drop'
  // decision, that check's own condition (`target === 'suggestions'`) is
  // simply false, so it does nothing — nothing downstream ever explicitly
  // rejects 'drop' at all, and execution falls straight through to a real
  // broadcast() call regardless of how low the score is. A far more
  // consequential gap than it looks: every 'drop'-classified detection
  // since useUnifiedScoring went live tonight was reaching the Candidates
  // panel unfiltered, not just the 3 entries the owner happened to
  // screenshot.
  if (target === 'drop') return false;

  // ── Suggestions dedup ─────────────────────────────────────────────────────
  // Drop verses already suggested within the window; if nothing new remains,
  // skip the broadcast entirely. Keeps repeated near-misses from flooding the
  // Candidates panel (and the WebSocket) on every search pass.
  if (target === 'suggestions') {
    if (recentSuggestions.size > 200) {
      for (const [k, t] of recentSuggestions) {
        if (now - t > SUGGESTION_DEDUP_MS) recentSuggestions.delete(k);
      }
    }
    verses = verses.filter(v => {
      const key  = `${v.book}|${v.chapter}|${v.verse}`;
      const last = recentSuggestions.get(key) || 0;
      if (now - last < SUGGESTION_DEDUP_MS) return false;
      recentSuggestions.set(key, now);
      return true;
    });
    if (!verses.length) return false;
  }

  // ── Deduplication (viewer-bound only) ─────────────────────────────────────
  // Prevents the same verse from flooding the SENT panel.
  // Exception 1: if the new verse is from the same book as the last sent verse
  // and arrives within SAME_BOOK_WINDOW_MS, always let it through — the preacher
  // is likely correcting or continuing in the same passage.
  // Exception 2: an explicit citation (method 'direct') is never suppressed by
  // a same-key send that came from a WEAKER method (verbatim/stream/etc.) —
  // only by a previous 'direct' send. Real incident: the anchor trie fired
  // "Luke 10:1" from a mid-citation fragment ("...verse one to two and"),
  // then moments later the reference parser correctly reconstructed the FULL
  // "Luke 10:1-2, 17-19" compound range from the joined segments — but
  // because it starts with the same verse 1, the dedup below silently
  // dropped the complete, authoritative citation in favor of the incomplete
  // guess that happened to land first.
  // Real incident (Joshua 1:18/1:8): a garbled 'direct' citation is
  // correctly overridden/corrected to the true verse (via the stale-override
  // guard above or maybeCorrectMiscitation), and moments later a FINAL
  // transcript segment re-parses the SAME underlying garbled words (a
  // joined-segment reconstruction retry) and produces a fresh 'direct' hit
  // for the exact OLD (wrong) reference again — 'direct' is normally
  // entitled to unconditionally bypass every dedup/continuity check below,
  // which let it silently overwrite the correction that had just landed.
  // See recentlyCorrectedAway's own declaration comment. Narrow and
  // time-boxed on purpose: only fires for the EXACT reference just corrected
  // away, only while its replacement is still the currently active one, and
  // only for a short window — a preacher genuinely re-citing the same verse
  // later is untouched.
  const reassertingCorrectedAwayRef = target === 'viewer' && method === 'direct' && recentlyCorrectedAway
    && topKey === recentlyCorrectedAway.key
    && now - recentlyCorrectedAway.at < RECENTLY_CORRECTED_WINDOW_MS
    && lastDetectedRef === recentlyCorrectedAway.replacedByKey;
  if (reassertingCorrectedAwayRef) {
    console.log(`[Guard] Blocked 'direct' re-send of "${verses[0].reference}" — already corrected to "${recentlyCorrectedAway.replacedByReference}" moments ago, that correction is still active — demoted to Candidates`);
    target = 'suggestions';
  }

  // Real incident (Isaiah 1:18/1:19, live 2026-09-13): "Isaiah 1:18" cited,
  // sent to viewer. Preacher keeps reading and says "...verse 19" — the bare
  // number correctly advances the display to Isaiah 1:19 via
  // resolvePartialReference (method 'direct-partial'). Moments later the
  // FINAL transcript's joined-segment reconstruction re-parses the WHOLE
  // utterance — which still opens with "...verse 18..." — and extracts
  // "Isaiah 1:18" as a fresh 'direct' hit (the first citation the parser
  // finds in that joined text). Being 'direct', it unconditionally bypasses
  // every gate below, including the backward-already-shown hard cap
  // (scoreCandidate's own isBackwardAlreadyShown, bugs #11/#12) that every
  // OTHER method is already subject to — so it silently dragged the display
  // back to the verse BEFORE the one the preacher had already progressed
  // past. This isn't a mis-hearing to correct (18 was never wrong) — it's a
  // stale internal reference re-surfacing from reconstructing text that's
  // already been fully processed and superseded by real, independent
  // forward progress. Same accepted tradeoff bugs #11/#12 already apply to
  // every non-direct method — extended here narrowly: only fires for the
  // exact shape of "same book/chapter, behind the current verse, AND that
  // behind verse was already shown before" — a genuinely fresh, later
  // re-citation of the same verse (a new utterance, not a reconstruction of
  // already-seen text) is a different broadcastDetection call entirely and
  // is untouched.
  const directBackwardAlreadyShown = target === 'viewer' && method === 'direct' && lastOutputVerse
    && verses[0].book    === lastOutputVerse.book
    && verses[0].chapter === lastOutputVerse.chapter
    && verses[0].verse   <  lastOutputVerse.verse
    && sentVerseKeysThisBook.has(topKey);
  if (directBackwardAlreadyShown) {
    console.log(`[Guard] Blocked 'direct' re-send of "${verses[0].reference}" — already superseded by "${lastOutputVerse.reference}" (real forward progress since), likely a joined-segment re-parse of already-processed text — demoted to Candidates`);
    target = 'suggestions';
  }

  if (target === 'viewer') {
    const dedupMs = method === 'direct' ? DIRECT_DEDUP_MS : DETECT_DEDUP_MS;
    const incomingBook = verses[0]?.book || null;
    const sameBookContinuation = incomingBook && incomingBook === lastSentBook
      && now - lastSentBookTime < SAME_BOOK_WINDOW_MS
      && topKey !== lastDetectedRef; // only bypass if it's actually a different verse
    const directOverridesWeaker = method === 'direct' && lastDetectedMethod !== 'direct';
    // Exception 3: a direct multi-verse citation that starts on the SAME verse
    // as what was already sent, but carries MORE verses than the range
    // currently queued, is a genuine reconstruction/extension — not a
    // redundant repeat — and Exception 2 above doesn't cover it, since both
    // sends are method:'direct'. Real incident: "Luke 10:1-2 and 17" arrives
    // as its own final segment (a complete-looking but truncated parse — a
    // trailing bare number always looks like a valid closed citation on its
    // own) and sends immediately; "to 19" then arrives as a separate final
    // segment, joins with the previous one, and correctly reconstructs the
    // full "1-2, 17-19" — but topKey is still "Luke|10|1" either way, so
    // this widened, corrected version was silently dropped by the dedup
    // below and 17-19 never reached the viewer at all. Self-limiting: once
    // this fires, setRangeQueue (called just before broadcastDetection, see
    // callers) already updated rangeAllVerses to the new wider set, so a
    // further attempt with the same or narrower verse count no longer
    // qualifies.
    const widerRangeExtension = method === 'direct' && verses.length > 1
      && topKey === lastDetectedRef && verses.length > rangeAllVerses.length;
    if (!sameBookContinuation && !directOverridesWeaker && !widerRangeExtension) {
      if (topKey && topKey === lastDetectedRef && now - lastDetectedTime < dedupMs) return false;
      // Real per-verse history check — see recentDetections' own comment.
      // Catches a stale repeat even when something else was detected in
      // between, which the lastDetectedRef check above alone cannot.
      if (topKey) {
        const lastSeenThisVerse = recentDetections.get(topKey);
        if (lastSeenThisVerse != null && now - lastSeenThisVerse < dedupMs) return false;
      }
    }
    if (topKey) {
      lastDetectedRef = topKey; lastDetectedTime = now; lastDetectedMethod = method;
      recentDetections.set(topKey, now);
      if (recentDetections.size > 100) {
        for (const [k, t] of recentDetections) if (now - t > DETECT_DEDUP_MS) recentDetections.delete(k);
      }
    }
  }

  if (target === 'viewer') {
    applyScriptureLanguage(verses);
    await attachBibleTranslations(verses);
  }
  broadcast({ type: 'detection', verses, method, topScore, target, timestamp: now });

  // Do NOT clear candidates on viewer send — candidates is now a permanent session log.

  if (target === 'viewer' && settings.autoSend !== false && verses[0]) {
    const vKey = `${verses[0].book}|${verses[0].chapter}|${verses[0].verse}`;
    if (vKey !== lastSentRef || now - lastSentTime >= SEND_DEDUP_MS) {
      lastSentBook     = verses[0].book;
      lastSentBookTime = now;
      if (method === 'direct') {
        lastDirectSentVerse = verses[0];
        lastDirectSentTime  = now;
        lastDirectSentWords = wordsHeard;
      }
      sendToOutputs(verses[0]).catch(err => console.warn('[Server] sendToOutputs failed:', err.message));
    }
  }
  // Return the actual landing spot ('viewer' or 'suggestions'), not just a
  // boolean — the continuity gate above can demote target to 'suggestions'
  // and still reach here successfully, so a plain `true` previously let
  // callers log "→ viewer" for something that had actually just been
  // redirected to Candidates in the same call.
  return target;
}

// ── Output routing — sends to all enabled destinations ───────────────────
async function sendToOutputs(verse) {
  if (!lastOutputVerse || lastOutputVerse.book !== verse.book) {
    sentVerseKeysThisBook = new Set();
  }
  sentVerseKeysThisBook.add(`${verse.book}|${verse.chapter}|${verse.verse}`);
  lastOutputVerse = verse;
  // Use the in-memory settings object (kept in sync by POST /api/settings)
  // rather than re-reading settings.json from disk on every single verse —
  // this runs on the detection hot path and disk I/O here adds latency
  // directly to seconds-to-screen.
  const tasks = [];
  if (settings.proPresenterEnabled !== false) tasks.push(sendToProPresenter(verse).catch(err => console.warn('[ProPresenter] send failed:', err.message)));
  if (settings.obsEnabled && obsConnected)    tasks.push(sendToOBS(verse).catch(err => console.warn('[OBS] send failed:', err.message)));
  await Promise.all(tasks);
}

// ── ProPresenter ──────────────────────────────────────────────────────────
let _ppCachedMsg = null;
let _ppCachedUrl = null;

async function sendToProPresenter(verse) {
  const url = settings.proPresenterUrl || 'http://localhost:1025';
  const t   = settings.translation || 'KJV';

  const vKey = `${verse.book}|${verse.chapter}|${verse.verse}`;
  const now  = Date.now();
  if (vKey === lastSentRef && now - lastSentTime < SEND_DEDUP_MS) return true;
  lastSentRef  = vKey;
  lastSentTime = now;

  const refLine   = `${verse.reference} (${t})`;
  const verseText = verse.text;
  const jsonHeaders = { headers: { 'Content-Type': 'application/json' }, timeout: 3000 };

  try {
    try {
      if (!_ppCachedMsg || _ppCachedUrl !== url) {
        const messagesRes = await axios.get(`${url}/v1/messages`, { timeout: 3000 });
        const messages    = Array.isArray(messagesRes.data) ? messagesRes.data : [];
        const scriptureMsg = messages.find(m => {
          const name = (m.id?.name || m.name || '').toLowerCase();
          return /scripture|bible|verse|kairo/.test(name);
        });
        if (scriptureMsg) {
          const msgId     = scriptureMsg.id?.uuid || scriptureMsg.uuid || scriptureMsg.id;
          const detailRes = await axios.get(`${url}/v1/message/${msgId}`, { timeout: 3000 });
          const tokens    = detailRes.data.tokens || detailRes.data.message?.tokens || [];
          _ppCachedMsg = { msgId, tokens };
          _ppCachedUrl = url;
        } else {
          _ppCachedMsg = null; _ppCachedUrl = url;
        }
      }

      if (_ppCachedMsg) {
        const { msgId, tokens } = _ppCachedMsg;
        const swapOrder = settings.ppSwapTokenOrder || false;
        let triggerTokens;

        if (tokens.length >= 2) {
          let refAssigned = false, textAssigned = false;
          const nameAttempt = tokens.map(tk => {
            const tName = (tk.name || tk.id?.name || '').toLowerCase();
            let value = null;
            if (!refAssigned && /ref|book|passage|location|cite|title|header|citation/i.test(tName)) {
              value = refLine; refAssigned = true;
            } else if (!textAssigned && /text|body|content|verse|scripture|lyric|line|quote/i.test(tName)) {
              value = verseText; textAssigned = true;
            }
            return { name: tk.name || tk.id?.name, value };
          });
          if (refAssigned && textAssigned) {
            triggerTokens = nameAttempt.map(t2 => ({ name: t2.name, text: { text: t2.value } }));
          } else {
            const first  = swapOrder ? refLine : verseText;
            const second = swapOrder ? verseText : refLine;
            triggerTokens = tokens.map((tk, idx) => ({
              name: tk.name || tk.id?.name,
              text: { text: idx === 0 ? first : idx === 1 ? second : '' },
            }));
          }
        } else if (tokens.length === 1) {
          const tokenName = tokens[0].name || tokens[0].id?.name || 'Text';
          triggerTokens = [{ name: tokenName, text: { text: `${refLine}\r\n${verseText}` } }];
        } else {
          triggerTokens = [
            { name: 'Reference', text: { text: refLine } },
            { name: 'Text',      text: { text: verseText } },
          ];
        }

        await axios.post(`${url}/v1/message/${msgId}/trigger`, JSON.stringify(triggerTokens), jsonHeaders);
        broadcast({ type: 'propresenter-success', verse: { reference: verse.reference, text: verseText } });
        return true;
      }
    } catch { _ppCachedMsg = null; _ppCachedUrl = null; }

    await axios.put(`${url}/v1/stage/message`, JSON.stringify(`${refLine}\r\n\r\n${verseText}`), jsonHeaders);
    broadcast({ type: 'propresenter-success', verse: { reference: verse.reference, text: verseText } });
    return true;

  } catch (err) {
    broadcast({ type: 'propresenter-error', error: err.message });
    return false;
  }
}

async function clearProPresenter() {
  const url = settings.proPresenterUrl || 'http://localhost:1025';
  try {
    if (_ppCachedMsg?.msgId) {
      await axios.delete(`${url}/v1/message/${_ppCachedMsg.msgId}/trigger`, { timeout: 3000 });
    }
  } catch {}
}

