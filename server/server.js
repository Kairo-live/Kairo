// ── Start ─────────────────────────────────────────────────────────────────
// Tauri normally hands us a free port via KAIRO_SERVER_PORT, so in production
// EADDRINUSE shouldn't happen. In dev (port 7777 hardcoded), we fail loudly
// rather than killing whatever else is on the port — that "fix" was a hazard
// to other dev servers and broke entirely on Windows.
function startListening() {
  server.listen(PORT, '127.0.0.1', () => {
    console.log(`[KAIRO] Server running at http://127.0.0.1:${PORT}` + (AUTH_REQUIRED ? ' (auth on)' : ''));
    spawnDetectionWorker();
  });
}

server.on('error', (err) => {
  if (err.code === 'EADDRINUSE') {
    console.error(`[KAIRO] Port ${PORT} is already in use.`);
    console.error('[KAIRO] Stop the process holding it (e.g. another Kairo instance) and retry.');
    process.exit(1);
  } else {
    console.error('[KAIRO] Server error:', err.message);
    process.exit(1);
  }
});

// Only auto-start when run directly (`node server/server.js`, or via
// npm run server / Tauri's beforeDevCommand) — required by the eval harness
// (server/eval/run_eval.js), which does `require('../server.js')` to call
// into the SAME functions the live path uses (handleTranscriptSegment,
// resetDetectionSession) rather than a reimplementation that could drift,
// without wanting a real Deepgram connection, OBS/ProPresenter polling, or
// an HTTP server bound to the live port.
if (require.main === module) {
  startListening();
} else {
  module.exports = {
    handleTranscriptSegment,
    resetDetectionSession,
    onBroadcast,
    workerReadyPromise,
    // startListening() binds an actual HTTP server on PORT (7777) as a side
    // effect of spawning the worker — the eval harness wants the worker
    // ONLY, no port bound (a real dev server may already be running on
    // 7777), so it calls this directly instead.
    spawnDetectionWorker,
    resolveAmbiguousRefs,
    // Exposed for direct, surgical regression tests (e.g. the Joshua 1:18/
    // 1:8 correction-override fix) that need to drive specific detection
    // candidates through the real gating/dedup logic without needing to
    // reconstruct real garbled ASR text that happens to score exactly right
    // through the full worker pipeline.
    broadcastDetection,
  };
}

// ── Graceful shutdown ─────────────────────────────────────────────────────
// Handles: Ctrl+C (SIGINT), Tauri kill (SIGTERM), terminal close (SIGHUP)
function gracefulShutdown(signal) {
  console.log(`[KAIRO] ${signal} received — shutting down…`);
  deepgramUserStopped = true;   // stop auto-reconnect loop immediately
  if (deepgramConnection) {
    try { deepgramConnection.requestClose(); } catch {}
    deepgramConnection = null;
  }
  if (deepgramKeepAliveTimer)  { clearInterval(deepgramKeepAliveTimer);  deepgramKeepAliveTimer  = null; }
  if (deepgramSilenceWatchdog) { clearInterval(deepgramSilenceWatchdog); deepgramSilenceWatchdog = null; }
  if (detectionWorker) {
    try { detectionWorker.terminate(); } catch {}
  }
  server.close(() => {
    console.log('[KAIRO] Server closed. Goodbye.');
    process.exit(0);
  });
  // Force-exit if graceful close hangs beyond 3s
  setTimeout(() => process.exit(0), 3000).unref();
}

process.on('SIGINT',  () => gracefulShutdown('SIGINT'));
process.on('SIGTERM', () => gracefulShutdown('SIGTERM'));
process.on('SIGHUP',  () => gracefulShutdown('SIGHUP'));   // terminal window closed

// ── Parent-process watchdog ───────────────────────────────────────────────
// When CMD+Q closes the Tauri app in dev mode, the Tauri CLI (our parent)
// dies but doesn't always send SIGTERM to children. Poll every 3s and exit
// if the parent is gone — prevents orphan servers holding port 7777.
// Only activate when running under a long-lived parent (Tauri CLI / nodemon).
// Short-lived parents (nohup shell, background &) die immediately — skip those.
const _startPpid = process.ppid;
setTimeout(() => {
  try {
    process.kill(_startPpid, 0); // parent still alive after 5s → long-lived
    setInterval(() => {
      try { process.kill(_startPpid, 0); }
      catch {
        console.log('[KAIRO] Parent process gone — shutting down…');
        gracefulShutdown('PARENT_GONE');
      }
    }, 3000).unref();
  } catch {
    // Parent already dead after 5s → we were launched standalone, skip watchdog
  }
}, 5000);
