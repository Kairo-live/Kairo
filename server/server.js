// ── Deepgram REST fallback ─────────────────────────────────────────────────
// Submits buffered audio to Deepgram REST API when the WebSocket drops
// mid-sermon. Catches the gap that would otherwise be silently lost.
async function submitDeepgramRestFallback() {
  if (!audioRingBuffer.length) return;
  const key = settings.deepgramApiKey;
  if (!key) return;

  // Only submit audio captured in the last 20s (avoid re-processing old audio)
  const cutoff     = Date.now() - 20000;
  const recentAudio = audioRingBuffer.filter(c => c.time >= cutoff);
  if (!recentAudio.length) return;

  console.log(`[Deepgram] REST fallback — submitting ${recentAudio.length} buffered chunks…`);
  const combined = Buffer.concat(recentAudio.map(c => c.data));

  try {
    const response = await axios.post(
      'https://api.deepgram.com/v1/listen?model=nova-2&language=en-US&smart_format=true&punctuate=true',
      combined,
      {
        headers: {
          'Authorization': `Token ${key}`,
          'Content-Type': 'audio/raw;encoding=linear16;sample_rate=16000;channels=1',
        },
        timeout: 15000,
      }
    );
    const transcript = response.data?.results?.channels?.[0]?.alternatives?.[0]?.transcript || '';
    if (transcript.trim()) {
      console.log('[Deepgram] REST fallback transcript:', transcript.slice(0, 100));
      broadcast({ type: 'transcript', text: transcript, isFinal: true, confidence: 0.9, source: 'rest-fallback' });
      // Run full detection pipeline on the recovered transcript
      await processForReferences(transcript, true);
      if (workerBasicReady) {
        await Promise.all([processVerbatim(transcript), runFingerprintSearch(transcript, true)]);
      }
    }
  } catch (err) {
    console.warn('[Deepgram] REST fallback failed:', err.message);
  }
}

// ── Range Queue ───────────────────────────────────────────────────────────
// When a verse range is detected (e.g. Matt 1:10-15), verse 1 auto-sends
// immediately. The remaining verses are queued.
//
// Auto-advance: on every transcript, if a range is active we run a targeted
// verbatim check specifically against the NEXT queued verse. If the preacher's
// speech matches it (similarity ≥ 0.70), it auto-sends — no operator click
// needed. The preacher's reading pace drives the navigation naturally.
//
// Manual advance: operator can still click "Next →" at any time (e.g. if the
// preacher skips a verse or the mic misses a line).
// Resolved per-output theme objects, mirrored from the client's own
// applyOutputThemes() broadcast (server.js has no independent notion of
// "themes" — it just remembers whatever the client last resolved and pushed).
// Used only to decide whether auto-detected/searched scripture needs a real
// Bible-translation lookup attached before broadcast — see attachBibleTranslations.
let currentOutputThemes = {};

// The Bible tab's "Translate to" language (settings.bibleTranslateTo) only
// does anything when the primary output is actually on the Multi-Language
// theme — otherwise there's no right-hand panel to fill.
function primaryOutputTranslateLang() {
  const primary = currentOutputThemes['display-1'];
  const lang = settings.bibleTranslateTo;
  if (!primary || primary.layout !== 'multi-language' || !lang) return null;
  return lang;
}

// Real verse text in the target language, looked up from the bundled
// public-domain translations (no API key needed) — mutates verses in place
// so every path sharing these object references picks it up once, whichever
// broadcast fires first. No-ops on anything already translated (e.g. a
// playlist item that resolved its own translatedText) or lacking book/chapter/
// verse (search's text/phrase fallback results).
async function attachBibleTranslations(verses) {
  const lang = primaryOutputTranslateLang();
  if (!lang) return verses;
  await Promise.all(verses.map(async (v) => {
    if (v.translatedText || !v.book || !v.chapter || !v.verse) return;
    try {
      const result = await translateText({
        text: v.text, lang,
        ref: { book: v.book, chapter: v.chapter, verse: v.verse },
      });
      v.translatedText = result.text || '';
    } catch (err) {
      console.warn('[Translate] Bible auto-translate failed:', err.message);
    }
  }));
  return verses;
}

