const OLLAMA_CALL_TIMEOUT_MS = 120_000;

// One chat call with schema-constrained output. Ollama ≥ 0.5 accepts a JSON
// schema in `format` and guarantees conforming output; older versions reject
// it, so retry once with plain JSON mode.
async function ollamaChat(system, user, schema) {
  const body = {
    model:   ollamaModel(),
    stream:  false,
    options: { temperature: 0.2, num_ctx: 8192 },
    messages: [
      { role: 'system', content: system },
      { role: 'user',   content: user },
    ],
  };
  let raw;
  try {
    const r = await axios.post(ollamaUrl() + '/api/chat', { ...body, format: schema },
      { timeout: OLLAMA_CALL_TIMEOUT_MS });
    raw = r.data?.message?.content || '';
  } catch (e) {
    if (!e.response || e.response.status < 400 || e.response.status >= 500) throw e;
    const r = await axios.post(ollamaUrl() + '/api/chat', { ...body, format: 'json' },
      { timeout: OLLAMA_CALL_TIMEOUT_MS });
    raw = r.data?.message?.content || '';
  }
  return JSON.parse(raw);   // throws on garbage — caller decides per chunk
}

function _contentNormWord(w) { return w.toLowerCase().replace(/[^a-z0-9]/g, ''); }

// Cut the transcript into per-scripture chunks. Returns null when there isn't
// enough structure to be worth it (fewer than 2 anchored verses).
function buildSermonChunks(session) {
  const oWords = String(session.transcript || '').split(/\s+/).filter(Boolean);
  if (oWords.length < MIN_CHUNK_WORDS * 2) return null;
  const nWords = oWords.map(_contentNormWord);

  // Transcript 4-gram → first word position (skip grams with empty tokens)
  const gramPos = new Map();
  for (let i = 0; i + 4 <= nWords.length; i++) {
    if (!nWords[i] || !nWords[i+1] || !nWords[i+2] || !nWords[i+3]) continue;
    const g = `${nWords[i]} ${nWords[i+1]} ${nWords[i+2]} ${nWords[i+3]}`;
    if (!gramPos.has(g)) gramPos.set(g, i);
  }

  // Anchor each verse at the earliest transcript position of any of its 4-grams
  const anchored = [];
  for (const v of (session.verses || [])) {
    const vw = String(v.text || '').split(/\s+/).map(_contentNormWord).filter(Boolean);
    let pos = null;
    for (let i = 0; i + 4 <= vw.length; i++) {
      const p = gramPos.get(`${vw[i]} ${vw[i+1]} ${vw[i+2]} ${vw[i+3]}`);
      if (p !== undefined && (pos === null || p < pos)) pos = p;
    }
    if (pos !== null) anchored.push({ ref: v.ref, text: v.text, pos });
  }
  if (anchored.length < 2) return null;
  anchored.sort((a, b) => a.pos - b.pos);

  // Chunk k runs from the midpoint before its anchor to the midpoint after.
  // First chunk absorbs the intro; last chunk runs to the end (closing).
  let chunks = anchored.map((a, k) => {
    const start = k === 0 ? 0 : Math.floor((anchored[k-1].pos + a.pos) / 2);
    const end   = k === anchored.length - 1
      ? oWords.length
      : Math.floor((a.pos + anchored[k+1].pos) / 2);
    return { verses: [a], start, end };
  });

  // Merge slivers into the previous chunk, then cap the total count by
  // repeatedly merging the smallest adjacent pair.
  chunks = chunks.filter((c, k) => {
    if (k > 0 && c.end - c.start < MIN_CHUNK_WORDS) {
      chunks[k-1].verses.push(...c.verses);
      chunks[k-1].end = c.end;
      return false;
    }
    return true;
  });
  while (chunks.length > MAX_MAP_CHUNKS) {
    let idx = 0, best = Infinity;
    for (let k = 0; k + 1 < chunks.length; k++) {
      const size = (chunks[k].end - chunks[k].start) + (chunks[k+1].end - chunks[k+1].start);
      if (size < best) { best = size; idx = k; }
    }
    chunks[idx].verses.push(...chunks[idx+1].verses);
    chunks[idx].end = chunks[idx+1].end;
    chunks.splice(idx + 1, 1);
  }

  return chunks.map(c => ({
    verses: c.verses,
    text:   oWords.slice(c.start, Math.min(c.end, c.start + CHUNK_WORD_CAP)).join(' '),
  }));
}

// Quote must be an exact fragment of the chunk — enforce, don't trust.
function _verifyQuote(quote, chunkText) {
  if (!quote) return null;
  const q = String(quote).trim();
  if (!q || q.split(/\s+/).length > 25) return null;
  const norm = s => s.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
  return norm(chunkText).includes(norm(q)) ? q : null;
}

async function generateStructured(session, type) {
  const chunks = buildSermonChunks(session);
  if (!chunks || chunks.length < 2) return null;   // short session → single-shot

  console.log(`[Content] Structured generation: ${chunks.length} chunks (${type})`);

  // MAP — one small extraction per chunk. A failed chunk is skipped, not fatal.
  const extracted = [];
  for (let k = 0; k < chunks.length; k++) {
    const c = chunks[k];
    const scriptureLine = c.verses
      .map(v => `${v.ref}: "${String(v.text || '').slice(0, 300)}"`)
      .join('\n') || '(none)';
    try {
      const out = await ollamaChat(
        CHUNK_PROMPT,
        `SCRIPTURE READ IN THIS SEGMENT:\n${scriptureLine}\n\nSEGMENT ${k + 1} OF ${chunks.length}:\n${c.text}`,
        CHUNK_SCHEMA,
      );
      if (out && out.point) {
        extracted.push({
          heading:         String(out.heading || '').slice(0, 120),
          point:           String(out.point || '').slice(0, 200),
          explanation:     String(out.explanation || '').slice(0, 1200),
          supportingQuote: _verifyQuote(out.supportingQuote, c.text),
          scriptures:      c.verses.map(v => v.ref),
        });
      }
    } catch (e) {
      console.warn(`[Content] Chunk ${k + 1}/${chunks.length} failed: ${e.message}`);
    }
    broadcast({ type: 'content-progress', done: k + 1, total: chunks.length + 1 });
  }
  if (extracted.length < 2) return null;   // not enough survived → single-shot

  // REDUCE — structure is assembled here, in preaching order; the model only
  // writes the connective prose around it.
  const outline = extracted
    .map((s, k) => `${k + 1}. ${s.heading} — ${s.point} [${s.scriptures.join(', ') || 'no scripture'}]`)
    .join('\n');

  let meta = {};
  try {
    meta = await ollamaChat(
      type === 'note' ? NOTE_META_PROMPT : POINTS_META_PROMPT,
      `SERMON OUTLINE:\n${outline}`,
      type === 'note' ? NOTE_META_SCHEMA : POINTS_META_SCHEMA,
    ) || {};
  } catch (e) {
    console.warn('[Content] Meta call failed, using fallbacks:', e.message);
  }
  broadcast({ type: 'content-progress', done: chunks.length + 1, total: chunks.length + 1 });

  const fallbackTitle = session.title || `Sermon — ${session.date || session.id}`;
  if (type === 'note') {
    return {
      title:   String(meta.title || fallbackTitle).slice(0, 200),
      summary: String(meta.summary || '').slice(0, 600),
      sections: extracted.map(s => ({
        heading:    s.heading,
        body:       s.supportingQuote ? `${s.explanation} — "${s.supportingQuote}"` : s.explanation,
        scriptures: s.scriptures,
      })),
      closing: String(meta.closing || '').slice(0, 400),
    };
  }
  return {
    title:     String(meta.title || fallbackTitle).slice(0, 200),
    mainTheme: String(meta.mainTheme || '').slice(0, 400),
    points: extracted.slice(0, 10).map(s => ({
      point:           s.point,
      explanation:     s.explanation,
      scripture:       s.scriptures[0] || null,
      supportingQuote: s.supportingQuote,
    })),
  };
}

app.post('/api/content/generate', async (req, res) => {
  const { sessionId, type } = req.body || {};
  if (!sessionId) return res.status(400).json({ error: 'sessionId required' });
  if (type !== 'note' && type !== 'points') return res.status(400).json({ error: 'type must be note|points' });

  const session = readSession(sessionId);
  if (!session) return res.status(404).json({ error: 'session not found' });
  if (!(session.transcript || '').trim()) {
    return res.status(400).json({ error: 'session has no transcript' });
  }

  const url = ollamaUrl();
  const model = ollamaModel();
  const allowed = (session.verses || []).map(v => v.ref);

  // ── Structured map/reduce path ──────────────────────────────────────────
  let parsed = null;
  try {
    parsed = await generateStructured(session, type);
  } catch (e) {
    console.warn('[Content] Structured generation failed — falling back to single-shot:', e.message);
  }

  // ── Single-shot fallback (short sessions, or structured path failed) ────
  if (!parsed) {
    const systemPrompt = type === 'note' ? NOTE_PROMPT : POINTS_PROMPT;
    let raw;
    try {
      const r = await axios.post(url + '/api/chat', {
        model,
        stream: false,
        format: 'json',
        options: { temperature: 0.2, num_ctx: 8192 },
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user',   content: buildUserPayload(session) },
        ],
      }, { timeout: 180_000 });
      raw = r.data?.message?.content || '';
    } catch (e) {
      const msg = e.response?.data?.error || e.code || e.message;
      return res.status(502).json({ error: `Ollama request failed: ${msg}`, url, model });
    }
    try { parsed = JSON.parse(raw); }
    catch { return res.status(502).json({ error: 'Model returned invalid JSON', raw: raw.slice(0, 500) }); }
  }

  const cleaned = type === 'note' ? sanitizeNote(parsed, allowed) : sanitizePoints(parsed, allowed);
  if (!cleaned) return res.status(502).json({ error: 'Model output failed validation' });

  session.generated = session.generated || {};
  session.generated[type] = { ...cleaned, generatedAt: new Date().toISOString(), model };
  session.updatedAt = new Date().toISOString();
  try { await writeSession(session); }
  catch (e) { return res.status(500).json({ error: e.message }); }

  res.json({ ok: true, type, content: session.generated[type] });
});

// ── DOCX export ───────────────────────────────────────────────────────────
// Renders a generated note/points document as a properly formatted Word file.
app.get('/api/content/export', async (req, res) => {
  const { sessionId, type } = req.query;
  if (!sessionId || (type !== 'note' && type !== 'points')) {
    return res.status(400).json({ error: 'sessionId and type=note|points required' });
  }
  const session = readSession(sessionId);
  const content = session?.generated?.[type];
  if (!content) return res.status(404).json({ error: 'no generated content — generate it in Content Studio first' });

  try {
    const { Document, Packer, Paragraph, TextRun, HeadingLevel } = require('docx');
    const children = [
      new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(content.title || 'Sermon')] }),
      new Paragraph({ children: [new TextRun({ text: session.date || '', italics: true, color: '666666' })] }),
      new Paragraph({ text: '' }),
    ];

    if (type === 'note') {
      if (content.summary) {
        children.push(new Paragraph({ children: [new TextRun({ text: content.summary, italics: true })] }),
                      new Paragraph({ text: '' }));
      }
      for (const s of (content.sections || [])) {
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(s.heading || '')] }));
        if (s.scriptures?.length) {
          children.push(new Paragraph({ children: [new TextRun({ text: s.scriptures.join('  ·  '), bold: true, color: '8B0000' })] }));
        }
        if (s.body) children.push(new Paragraph({ children: [new TextRun(s.body)] }));
        children.push(new Paragraph({ text: '' }));
      }
      if (content.closing) {
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun('Closing')] }),
                      new Paragraph({ children: [new TextRun({ text: content.closing, italics: true })] }));
      }
    } else {
      if (content.mainTheme) {
        children.push(new Paragraph({ children: [new TextRun({ text: content.mainTheme, italics: true })] }),
                      new Paragraph({ text: '' }));
      }
      (content.points || []).forEach((p, i) => {
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(`${i + 1}. ${p.point || ''}`)] }));
        if (p.scripture) {
          children.push(new Paragraph({ children: [new TextRun({ text: p.scripture, bold: true, color: '8B0000' })] }));
        }
        if (p.explanation) children.push(new Paragraph({ children: [new TextRun(p.explanation)] }));
        if (p.supportingQuote) {
          children.push(new Paragraph({ children: [new TextRun({ text: `"${p.supportingQuote}"`, italics: true, color: '444444' })] }));
        }
        children.push(new Paragraph({ text: '' }));
      });
    }

    const doc = new Document({ sections: [{ children }] });
    const buf = await Packer.toBuffer(doc);
    const safeDate = (session.date || session.id || '').replace(/[^A-Za-z0-9_\-]/g, '-');
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
    res.setHeader('Content-Disposition', `attachment; filename="KAIRO_${type}_${safeDate}.docx"`);
    res.send(buf);
  } catch (e) {
    console.error('[Content] DOCX export failed:', e.message);
    res.status(500).json({ error: e.message });
  }
});

// ── Shared transcript pipeline ───────────────────────────────────────────
// Called by both the Deepgram WebSocket handler and the /api/stream-text
// endpoint (browser Web Speech API path). Broadcasts the transcript to
// clients, runs reference detection on interim + final, and dispatches
// verbatim / fingerprint / streaming-anchor searches on final segments.
//
// `speechFinal` signals utterance boundary — for Deepgram it's their
// endpointing flag; for browser Web Speech API we set it = isFinal, since
// each final result is its own utterance.
async function handleTranscriptSegment(transcript, isFinal, confidence, speechFinal) {
  broadcast({ type: 'transcript', text: transcript, isFinal, confidence });

  // Monotonic "how much has actually been said" counter — final segments
  // only (interim resends a growing, overlapping prefix of the same
  // utterance, so counting those would inflate this per utterance rather
  // than per word). See CORRECTION_WINDOW_WORDS for why this exists instead
  // of a wall-clock timer.
  if (isFinal && transcript) wordsHeard += transcript.trim().split(RE_SPACES).filter(Boolean).length;

  // ── Interim transcripts ───────────────────────────────────────
  // Reference parser fires on interim for < 2s explicit citations.
  // Fingerprint also fires on longer interim segments so paraphrase
  // detection doesn't wait for the endpoint (300-1200ms delay).
  if (!isFinal) {
    // Feed new words into the anchor trie immediately — don't wait for the
    // final. Quotes start matching while the preacher is mid-sentence.
    // Skipped for Whisper: its onPartial re-transcribes the entire growing
    // audio window from scratch every pass (no stable append-only prefix
    // guarantee the way Deepgram's interim API has), so the word-count-based
    // watermark diff in streamNewWords can't tell a genuine new word from an
    // earlier word whisper silently revised. Feeding a revised tail into the
    // anchor trie's persistent alignment state produces false sequential
    // matches — wrong verses reaching the viewer before the utterance even
    // finishes. The trie still gets the (stable, one-shot) final text below.
    if (!whisperActive) streamNewWords(transcript, false);
    maybeHandleNextVerseTrigger(transcript).catch(() => {});
    maybeAdvanceRangeOnLastWords(transcript);
    if (workerBasicReady) {
      let foundRef = await processForReferences(transcript, false);
      if (!foundRef && referenceContext.isValid) {
        const partial = resolvePartialReference(transcript);
        if (partial && partial.verse) {
          try {
            const msg = await workerCall('directLookup', { book: partial.book, chapter: partial.chapter, verse: partial.verse }, 3000);
            if (msg.result) {
              // 'direct-partial', not 'direct' — this is a bare "verse N"
              // resolved against a book/chapter cited up to CONTEXT_EXPIRE_MS
              // ago, not a fresh explicit citation. It goes through the same
              // continuity gate as verbatim/stream hits instead of bypassing
              // it, and is logged (previously this whole path was silent —
              // the exact combination that let a stale-context misfire reach
              // the live screen with zero trace in the logs).
              const sent = await broadcastDetection([msg.result], 'direct-partial', DIRECT_PARTIAL_SCORE, 'viewer');
              if (sent === 'viewer') console.log(`[Context] Interim partial ref "verse ${partial.verse}" → ${msg.result.reference}`);
              foundRef = true;
            }
          } catch {}
        }
      }
      if (!foundRef) {
        const interimWords = transcript.split(RE_SPACES).filter(Boolean).length;
        const now = Date.now();
        // Same Whisper caveat as streamNewWords above: onPartial re-transcribes
        // the whole growing audio window from scratch, so an interim segment
        // isn't a stable prefix — it can contain revised/hallucinated words
        // that happen to line up with an unrelated verse. Verbatim/fingerprint
        // only ever run against Whisper's settled final text below.
        if (!whisperActive && interimWords >= 6 && now - lastInterimVerbatim > INTERIM_VERBATIM_MS) {
          lastInterimVerbatim = now;
          processVerbatim(transcript).catch(err => console.warn('[Detection] processVerbatim failed:', err.message));
        }
        if (!whisperActive && interimWords >= 6 && now - lastFingerprintSearch > FINGERPRINT_INTERVAL_MS) {
          lastFingerprintSearch = now;
          runFingerprintSearch(transcript, true);
        }
        if (!whisperActive && interimWords >= 6 && now - lastSemanticSearch > SEMANTIC_INTERVAL_MS) {
          lastSemanticSearch = now;
          runSemanticSearch(transcript);
        }
      }
    }
    return;
  }

  // ── Final transcript ───────────────────────────────────────────
  const now = Date.now();
  const wordCount = transcript.split(/\s+/).filter(Boolean).length;
  transcriptBuffer.push({ text: transcript, time: now, wordCount });
  while (transcriptBuffer.length && transcriptBuffer[0].time < now - 90000) transcriptBuffer.shift();
  hasNewTranscript = true;

  streamNewWords(transcript, true);
  maybeHandleNextVerseTrigger(transcript).catch(() => {});
  markVerseEndIfJustFinished(transcript);

  accumulateTopicWords(transcript);
  maybeRebuildTopicLibrary();

  maybeAdvanceRangeOnLastWords(transcript);

  let foundRef = await processForReferences(transcript, true);

  if (!foundRef && referenceContext.isValid) {
    const partial = resolvePartialReference(transcript);
    if (partial) {
      try {
        let verses = [];
        if (partial.verseStart && partial.verseEnd && partial.verseEnd !== partial.verseStart) {
          const msg = await workerCall('rangeLookup', { book: partial.book, chapter: partial.chapter, verseStart: partial.verseStart, verseEnd: partial.verseEnd }, 3000);
          verses = msg.results || [];
        } else if (partial.verse) {
          const msg = await workerCall('directLookup', { book: partial.book, chapter: partial.chapter, verse: partial.verse }, 3000);
          if (msg.result) verses = [msg.result];
        }
        if (verses.length) {
          // 'direct-partial', not 'direct' — see the interim resolvePartialReference
          // call above for why this goes through the continuity gate instead of
          // bypassing it. Logged after the call, gated on the actual landing
          // target so this can't claim a viewer-send that was really demoted.
          if (verses.length > 1) setRangeQueue(verses);
          else clearRangeQueue();
          const sent = await broadcastDetection(verses, 'direct-partial', DIRECT_PARTIAL_SCORE, 'viewer');
          if (sent === 'viewer') console.log(`[Context] Resolved partial ref "verse ${partial.verse || partial.verseStart}" → ${partial.book} ${partial.chapter}:${partial.verse || partial.verseStart}`);
          foundRef = true;
        }
      } catch (err) {
        console.warn('[Context] Partial ref lookup error:', err.message);
      }
    }
  }

  if (!foundRef) {
    foundRef = maybeHandleBareVerseNumber(transcript);
  }

  // Only tried once the exact +1 continuation above has already had its
  // shot — that one's narrower match (must equal current+1 exactly) makes
  // it the safer, more specific read of an ambiguous trailing number.
  if (!foundRef) {
    foundRef = await maybeHandleVerseEndNumberJump(transcript);
  }

  if (transcriptBuffer.length) {
    transcriptBuffer[transcriptBuffer.length - 1].hasRef = !!foundRef;
  }

  // During active scripture reading (range is on-screen) skip the sentence
  // buffer entirely — run verbatim on every final segment so end-of-verse
  // transitions feel immediate rather than waiting up to 4 s for punctuation.
  let textForExpensive;
  if (rangeCurrentVerse && workerBasicReady) {
    sentenceBuffer.forceFlush();   // discard any partial accumulation
    textForExpensive = transcript;
    const canFingerprint = now - lastFingerprintSearch > FINGERPRINT_INTERVAL_MS;
    lastFingerprintSearch = now;
    const canSemantic = now - lastSemanticSearch > SEMANTIC_INTERVAL_MS;
    if (canSemantic) lastSemanticSearch = now;
    await Promise.all([
      processVerbatim(textForExpensive),
      canFingerprint
        ? runFingerprintSearch(textForExpensive, true)
        : Promise.resolve(),
      canSemantic
        ? runSemanticSearch(textForExpensive)
        : Promise.resolve(),
    ]);
  } else {
    const sentenceFlushed = speechFinal
      ? sentenceBuffer.forceFlush()
      : sentenceBuffer.append(transcript);
    textForExpensive = sentenceFlushed || sentenceBuffer.checkTimeout();

    if (workerBasicReady && textForExpensive) {
      const canFingerprint = now - lastFingerprintSearch > FINGERPRINT_INTERVAL_MS;
      lastFingerprintSearch = now;
      const canSemantic = now - lastSemanticSearch > SEMANTIC_INTERVAL_MS;
      if (canSemantic) lastSemanticSearch = now;
      await Promise.all([
        processVerbatim(textForExpensive),
        canFingerprint
          ? runFingerprintSearch(textForExpensive, true)
          : Promise.resolve(),
        canSemantic
          ? runSemanticSearch(textForExpensive)
          : Promise.resolve(),
      ]);
    } else if (workerBasicReady && !textForExpensive) {
      const interimWords = transcript.split(/\s+/).filter(Boolean).length;
      if (interimWords >= 8) {
        processVerbatim(transcript).catch(err => console.warn('[Detection] processVerbatim failed:', err.message));
      }
    }
  }

  if (speechFinal && workerBasicReady) {
    // Last ~60 words only. Re-searching the full 90s buffer cost 200-500ms of
    // worker time per utterance and queued ahead of direct reference lookups;
    // anything older than ~60 words was already covered by earlier passes.
    const bufferText = transcriptBuffer.map(t => t.text).join(' ')
      .split(RE_SPACES).slice(-60).join(' ').trim();
    if (bufferText && bufferText !== textForExpensive) {
      await Promise.all([
        processVerbatim(bufferText),
        runFingerprintSearch(bufferText, true),
      ]);
    }
  }
}

// ── Whisper (offline STT, whisper.cpp) ─────────────────────────────────────
// Local, no-internet engine. Audio streams from the client over the same
// WebSocket the Deepgram path uses. Results are routed through the shared
// `handleTranscriptSegment` so detection / broadcast / viewer behaviour is
// identical to Deepgram.
let whisperMod    = null;   // require('./whisper_engine'), loaded once
let whisperEngine = null;   // WhisperEngine instance
let whisperActive = false;
let whisperLastPartial = '';

function loadWhisperMod() {
  if (whisperMod) return whisperMod;
  whisperMod = require('./whisper_engine');   // pure JS, always requireable
  return whisperMod;
}

async function startWhisper() {
  if (connectionState === 'connected' || connectionState === 'connecting') {
    return { error: 'Already listening' };
  }
  try {
    connectionState = 'connecting';
    broadcast({ type: 'connection-state', state: 'connecting', engine: 'whisper' });

    const { WhisperEngine, defaultModelPath } = loadWhisperMod();
    whisperLastPartial = '';
    whisperEngine = new WhisperEngine({
      modelPath: process.env.KAIRO_WHISPER_MODEL || defaultModelPath(),
      gpu: true,
      language: 'en',
      onPartial: (text) => {
        const t = (text || '').trim();
        if (!t || t === whisperLastPartial) return;
        whisperLastPartial = t;
        handleTranscriptSegment(t, false, 0.85, false).catch(() => {});
      },
      onFinal: (text) => {
        const t = (text || '').trim();
        whisperLastPartial = '';
        if (t) handleTranscriptSegment(t, true, 0.9, true).catch(() => {});
      },
      onError: (err) => console.warn('[Whisper]', err.message),
    });

    await whisperEngine.start();
    whisperActive = true;
    streamWatermark = 0;
    connectionState = 'connected';
    broadcast({ type: 'connection-state', state: 'connected', engine: 'whisper' });
    return { ok: true, engine: 'whisper' };
  } catch (err) {
    whisperActive = false;
    whisperEngine = null;
    connectionState = 'error';
    const friendly = err.code === 'WHISPER_MODEL_MISSING'
      ? 'Offline model missing. Run "npm run whisper:install" to download it (~182MB), or wait for the startup download to finish.'
      : err.code === 'WHISPER_BINDING_MISSING'
      ? 'Offline engine not installed. Run "npm install" in the server folder.'
      : `Whisper failed to start: ${err.message}`;
    broadcast({ type: 'connection-state', state: 'error', error: friendly, errorKind: err.code === 'WHISPER_MODEL_MISSING' ? 'model-missing' : 'unknown' });
    return { error: friendly };
  }
}

function feedWhisperAudio(buffer) {
  if (!whisperActive || !whisperEngine) return;
  try { whisperEngine.feed(buffer); }
  catch (err) { console.warn('[Whisper] feed error:', err.message); }
}

