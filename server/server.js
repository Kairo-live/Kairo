// ── Spoken bare-number continuation ───────────────────────────────────────
// Reading a passage aloud, preachers often stop saying "verse" once the
// book/chapter has been cited — "Acts seven fifty... fifty-one...
// fifty-two..." with nothing but the bare number between them. Treat a
// final segment that TRAILS OFF with a number equal to (currently displayed
// verse) + 1 the same way as the "next verse" keyword.
//
// Checks the tail, not the whole utterance — real STT usually glues a quick
// "51" onto the end of whatever was just read ("...so do you, 51") rather
// than giving it its own isolated final segment, so requiring the entire
// segment to be nothing but the number missed exactly this case in testing.
//
// Still deliberately narrow so it can't misfire on an unrelated number
// mentioned mid-sentence ("that's been true for thirty years"): the number
// must be the LAST thing spoken (nothing trails after it — "thirty years"
// fails because "years" follows), and it must equal the expected next verse
// exactly — no jumps, no guessing.
const BARE_NUMBER_FILLER      = new Set(['and', 'so', 'now', 'okay', 'ok', 'verse', 'verses', 'next']);
const BARE_NUMBER_COOLDOWN_MS = 2000;
const BARE_NUMBER_TAIL_WORDS  = 4;   // how far back to look for a trailing number
let lastBareNumberAt = 0;

function maybeHandleBareVerseNumber(transcript) {
  const now = Date.now();
  if (now - lastBareNumberAt < BARE_NUMBER_COOLDOWN_MS) return false;

  // Keep digits (Deepgram/Whisper often render spoken numbers as "51" in
  // the transcript, not the words "fifty one") — RE_NONALPHA strips those,
  // so this uses its own alnum-preserving cleanup instead.
  const words = transcript.toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(RE_WHITESPACE, ' ')
    .trim()
    .split(' ')
    .filter(Boolean);
  if (!words.length) return false;

  const tail = words.slice(-BARE_NUMBER_TAIL_WORDS).filter(w => !BARE_NUMBER_FILLER.has(w));
  if (!tail.length) return false;

  // Try every starting point in the tail, preferring the longest (earliest)
  // match — the number must consume all the way to the end of the tail, i.e.
  // be the very last thing said, with nothing after it.
  let num = null;
  for (let start = 0; start < tail.length; start++) {
    const n = consumeNumber(tail, start);
    if (n && start + n.consumed === tail.length) { num = n; break; }
  }
  if (!num) return false;

  const base = rangeCurrentVerse || lastOutputVerse;
  if (!base?.book || !base.chapter || base.verse == null) return false;
  if (num.value !== base.verse + 1) return false;

  lastBareNumberAt = now;

  if (rangeQueue.length) {
    requestRangeAdvance(`Bare-number continuation "${num.value}"`);
    return true;
  }

  workerCall('directLookup', { book: base.book, chapter: base.chapter, verse: num.value }, 3000)
    .then(msg => {
      if (msg.result) {
        console.log(`[NextVerse] Bare number "${num.value}" → ${msg.result.reference}`);
        broadcastDetection([msg.result], 'direct', 1.0, 'viewer');
      }
    })
    .catch(() => {});
  return true;
}

// ── Verse-end detection → bare-number "jump to verse N" ────────────────────
// The bare-number continuation above only ever accepts exactly current+1
// (pure sequential reading). This covers the other real case: a preacher
// who finishes reading the verse on screen, then calls out a SPECIFIC verse
// number to jump to ("...so do you. Now go to verse twenty-five!") rather
// than reading straight through. Since the accepted value isn't constrained
// to +1 here, a bare number alone isn't enough signal on its own — it's
// gated on having just genuinely finished the on-screen verse (its own last
// 3 meaningful words showing up in speech), the same principle the range-
// advance "last-2-words" check above already uses, just generalized to any
// currently-displayed verse (not only a formal multi-verse range) and
// widened from 2 words to 3 for a slightly stronger signal given the wider
// blast radius (any verse, not just +1).
let verseEndDetectedAt = 0;
const VERSE_END_NUMBER_WINDOW_MS = 8000;   // how long a finish-read stays "live" for a follow-up number
const VERSE_JUMP_MAX_WORDS       = 4;      // "now verse twenty five" — leaves headroom without accepting a whole sentence
let lastVerseJumpAt = 0;
const VERSE_JUMP_COOLDOWN_MS = 2000;

function markVerseEndIfJustFinished(transcript) {
  const base = lastOutputVerse;
  const text = base?.text || base?.kjv_text;
  if (!text) return;
  const tail3 = getLastMeaningfulWords(text, 3);
  if (!tail3) return;
  if (meaningfulWords(transcript).join(' ').includes(tail3)) verseEndDetectedAt = Date.now();
}

// ── Last-2-words end-of-verse detection (range auto-advance) ───────────────
// If a range is active, check whether this transcript contains the last two
// meaningful words of the currently-displayed verse. This is the ONLY range
// auto-advance trigger — a timing-based estimator (words-per-second × verse
// length) used to run alongside this, but it measured pace from the last
// 15s of ALL speech, including tangents. A preacher who reads a verse then
// explains it for a minute talks at a normal (often faster) conversational
// pace while explaining — the estimator read that as "fast reader" and
// advanced the display to the next verse while they were still mid-
// explanation of the current one. Matching the last two words the preacher
// actually finished reading has no such failure mode: it only fires when
// they've genuinely said the end of the verse, however long that takes.
//
// Previously only called from the FINAL-transcript path, which meant it
// could only react once Deepgram's endpointing had already closed out the
// segment — an extra few hundred ms to a second-plus of pure waiting, on
// top of however long the words themselves took to arrive. Direct-citation
// detection doesn't pay that tax (it already runs on interim text too), so
// range-advance was measurably slower to react than a fresh citation despite
// being the simpler case. Now called from both interim and final so it
// reacts the moment the words are heard, same as everything else.
function maybeAdvanceRangeOnLastWords(transcript) {
  const now = Date.now();
  if (!(rangeCurrentVerse && rangeQueue.length && !rangeAdvancing
      && now - rangeLastAdvanceAt >= RANGE_ADVANCE_COOLDOWN_MS)) return;
  const tail2 = getLastMeaningfulWords(
    rangeCurrentVerse.text || rangeCurrentVerse.kjv_text || '', 2
  );
  if (!tail2) return;
  // Filter the transcript through the SAME stop-word removal as tail2 (see
  // meaningfulWords) — a raw substring check would require "heaven" and
  // "earth" to be literally adjacent, but the actual spoken verse has "and
  // the" between them, same as the source text does.
  const transcriptMeaningful = meaningfulWords(transcript).join(' ');
  if (transcriptMeaningful.includes(tail2)) {
    requestRangeAdvance(`Last-2-words advance: "${tail2}" detected`);
  }
}

async function maybeHandleVerseEndNumberJump(transcript) {
  if (!verseEndDetectedAt || Date.now() - verseEndDetectedAt > VERSE_END_NUMBER_WINDOW_MS) return false;
  const now = Date.now();
  if (now - lastVerseJumpAt < VERSE_JUMP_COOLDOWN_MS) return false;

  const base = lastOutputVerse;
  if (!base?.book || !base.chapter) return false;

  // The number must be essentially the WHOLE segment (filler words aside) —
  // not just present somewhere in it. A number buried in unrelated speech
  // ("that's been true for twenty-five years") is exactly the false-
  // positive case this guard exists to rule out, even inside the post-
  // verse window.
  const words = transcript.toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(RE_WHITESPACE, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .filter(w => !BARE_NUMBER_FILLER.has(w));
  if (!words.length || words.length > VERSE_JUMP_MAX_WORDS) return false;

  const num = consumeNumber(words, 0);
  if (!num || num.consumed !== words.length) return false;
  if (num.value === base.verse) return false;   // already the verse on screen — nothing to do

  verseEndDetectedAt = 0;   // consume — a second stray number shouldn't jump again off the same finish
  lastVerseJumpAt = now;

  try {
    const msg = await workerCall('directLookup', { book: base.book, chapter: base.chapter, verse: num.value }, 3000);
    if (msg.result) {
      console.log(`[VerseJump] End-of-verse number "${num.value}" → ${msg.result.reference}`);
      clearRangeQueue();   // jumping to an arbitrary verse breaks any active sequential range
      broadcastDetection([msg.result], 'direct', 1.0, 'viewer');
      return true;
    }
  } catch {}
  return false;
}

// Timing-based range auto-advance (estimated words-per-second × verse length)
// used to live here. Removed: it measured pace from the last 15s of ALL
// speech, including tangents — a preacher who reads a verse then spends a
// minute explaining it talks at a normal (often faster) conversational pace
// while explaining, which the estimator read as "fast reader" and advanced
// the display to the next verse mid-explanation of the current one.
// Last-2-words detection (below) is now the only range auto-advance trigger
// — it only fires once the preacher has genuinely said the end of the
// verse, however long that takes to get to.

// ── Topic Accumulator ─────────────────────────────────────────────────────
// Listens to the rolling speech stream and builds a topic word frequency map.
// Every 60s it extracts the top recurring content words and sends them to
// the worker to rebuild the topic library.
//
// The library is ready within 2-5 minutes of the sermon starting — by the
// time the preacher quotes anything substantive, the system already knows
// the thematic territory it's operating in.
//
// "Forgiveness, mercy, cleanse, restore" repeated across 3 minutes
//   → topic words: [forgiveness, mercy, cleanse, restore, iniquity, ...]
//   → worker builds library of top 80 matching verses
//   → fingerprint now searches 80 verses, not 31,000

const TOPIC_BUILD_INTERVAL_MS = 60 * 1000;   // rebuild every 60s
const TOPIC_WORD_MIN_COUNT     = 2;           // word must appear ≥ 2× to qualify
const TOPIC_WORD_MIN_IDF       = 3.0;         // only distinctive words (IDF threshold)
const TOPIC_MAX_WORDS          = 20;          // top 20 words drive the library
// Counts are halved each rebuild (~60s). Gives recent speech ~2 min of
// effective memory, bounds the map to the recent working set, and lets the
// topic library follow the current passage instead of locking onto early
// vocabulary. See maybeRebuildTopicLibrary for why this fixes the slowdown.
const TOPIC_DECAY_FACTOR       = 0.5;

let topicWordCounts   = new Map();   // Map<word, count> — raw frequency from speech
let lastTopicBuild    = 0;

// Called on every final transcript — accumulates word frequencies
function accumulateTopicWords(transcript) {
  const norm = s => s.toLowerCase().replace(RE_NONALPHA, '').replace(RE_WHITESPACE, ' ').trim();
  const words = norm(transcript).split(' ')
    .filter(w => w.length >= 5);   // 5+ chars — skips most noise words naturally
  for (const w of words) {
    topicWordCounts.set(w, (topicWordCounts.get(w) || 0) + 1);
  }
}

// Extracts qualifying topic words and triggers a library build if due
async function maybeRebuildTopicLibrary() {
  const now = Date.now();
  if (now - lastTopicBuild < TOPIC_BUILD_INTERVAL_MS) return;
  lastTopicBuild = now;

  // Extract words that appear frequently AND are topically distinctive.
  // We ask the worker for IDF scores via a workerCall so we don't duplicate
  // the IDF map in server memory — the worker owns all Bible data.
  const candidates = [...topicWordCounts.entries()]
    .filter(([, count]) => count >= TOPIC_WORD_MIN_COUNT)
    .map(([word]) => word);

  // Decay every count and evict words that have faded below the floor. This is
  // what keeps topicWordCounts bounded AND makes the library track the current
  // passage: without it the map grows for the whole service and early-sermon
  // vocabulary dominates forever, while the per-rebuild filter/sort +
  // getIdfScores worker call (on the detection thread) gets steadily heavier —
  // the source of the "matching slows as service progresses" stall. Runs once
  // per build interval, so it's O(map) at most every 60s. We decay *after*
  // snapshotting candidates so this build still uses the full recent counts.
  for (const [word, count] of topicWordCounts) {
    const decayed = count * TOPIC_DECAY_FACTOR;
    if (decayed < 1) topicWordCounts.delete(word);
    else topicWordCounts.set(word, decayed);
  }

  if (candidates.length < 3) return;   // not enough signal yet — too early in sermon

  try {
    // Get IDF scores for candidates from worker, filter by threshold
    const msg = await workerCall('getIdfScores', { words: candidates }, 3000);
    const topicWords = (msg.words || [])
      .filter(([, idf]) => idf >= TOPIC_WORD_MIN_IDF)
      .sort((a, b) => {
        // Rank by frequency × IDF — words that are both common in speech AND distinctive in Bible
        const freqA = topicWordCounts.get(a[0]) || 0;
        const freqB = topicWordCounts.get(b[0]) || 0;
        return (freqB * b[1]) - (freqA * a[1]);
      })
      .slice(0, TOPIC_MAX_WORDS)
      .map(([word]) => word);

    if (topicWords.length < 2) return;

    const buildMsg = await workerCall('buildTopicLibrary', { topicWords }, 5000);
    if (buildMsg.size > 0) {
      console.log(`[Topic] Library rebuilt: ${buildMsg.size} verses for topic [${topicWords.slice(0, 4).join(', ')}...]`);
      broadcast({ type: 'topic-library', size: buildMsg.size, words: topicWords.slice(0, 6) });
    }
  } catch (err) {
    if (!err.message?.includes('timeout')) console.warn('[Topic] Library build error:', err.message);
  }
}

function resetTopicAccumulator() {
  topicWordCounts.clear();
  lastTopicBuild = 0;
}

// ── Sermon Context Accumulator ────────────────────────────────────────────
// A real sermon visits 30-50 scriptures across 20+ books in an hour.
// The preacher moves fast — sometimes 7 references in 2 minutes.
//
// The model: track the last 8 explicitly cited verses with timestamps.
// Context hint = that sliding citation window.
//
// In the worker, verses that are *neighbors* of recently cited verses
// (same chapter, within ±5 verses) get a gentle tie-breaker boost — max
// 1.15×. This resolves genuine ambiguity without overriding word match.
//
// The 87% fingerprint word score is always primary. Context only tips the
// scale when two candidates are very close.

const CONTEXT_WINDOW_MS  = 5 * 60 * 1000;   // citations older than 5 min expire
const CONTEXT_MAX_CITED  = 8;                // keep last 8 cited verses

const recentCitations = [];   // [{ book, chapter, verse, time }, ...]

function updateSermonContext(ref) {
  const now = Date.now();
  recentCitations.push({
    book:    ref.book,
    chapter: ref.chapter || null,
    verse:   ref.verse   || ref.verseStart || null,
    time:    now,
  });
  // Keep only the last N within the window
  const cutoff = now - CONTEXT_WINDOW_MS;
  while (recentCitations.length > CONTEXT_MAX_CITED ||
         (recentCitations.length > 0 && recentCitations[0].time < cutoff)) {
    recentCitations.shift();
  }
}

function getContextHint() {
  if (!recentCitations.length) return null;
  const now    = Date.now();
  const cutoff = now - CONTEXT_WINDOW_MS;
  // Return only citations still within the window, most recent first
  const active = recentCitations
    .filter(c => c.time >= cutoff)
    .map(c => ({ ...c, age: now - c.time }))
    .reverse();
  return active.length ? { citations: active } : null;
}

function resetSermonContext() {
  recentCitations.length = 0;
}

